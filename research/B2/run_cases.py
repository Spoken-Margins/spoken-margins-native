"""Run every case in urls.json through today's Follow checks and the Substack resolver.

  python3 run_cases.py            replay from fixtures/ (offline), print the table
  python3 run_cases.py --record   fetch live, store new fixtures, then the same
  python3 run_cases.py --write    also rewrite results.md

For an article item the reference the app stores depends on how it was added
(see README): the Safari extension and the Link field store the page's final
location.href (query and fragment kept); the share sheet stores
<link rel=canonical> when present. Both are derived from the recorded page.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.parse
from pathlib import Path

from current_app import CurrentApp
from fetcher import Fetcher, RedirectRefused
from substack_resolver import SubstackResolver

HERE = Path(__file__).resolve().parent
CANONICAL = re.compile(r"<link[^>]*rel=\"canonical\"[^>]*href=\"([^\"]+)\"", re.I)


def item_references(fetcher: Fetcher, url: str) -> dict:
    """What externalReference an article item would get from each import path."""
    https_url = re.sub(r"^http://", "https://", url, flags=re.I)
    fragment = urllib.parse.urlsplit(https_url).fragment
    try:
        page = fetcher.get(urllib.parse.urlsplit(https_url)._replace(fragment="").geturl(), "html")
    except RedirectRefused:
        return {"safari": https_url, "share": https_url}
    safari = page.url + (f"#{fragment}" if fragment else "")
    canonical = CANONICAL.search(page.body)
    return {"safari": safari, "share": canonical.group(1) if canonical else safari}


def run(mode: str) -> list:
    fetcher = Fetcher(mode)
    app, resolver = CurrentApp(fetcher), SubstackResolver(fetcher)
    cases = json.loads((HERE / "urls.json").read_text())["cases"]
    rows = []
    for case in cases:
        row = {"id": case["id"], "category": case["category"], "url": case["url"],
               "expect_feed": case["expect_feed"]}
        row["following_tab"] = app.following_tab(case["url"])
        if case["item"]:
            refs = item_references(fetcher, case["url"])
            row["refs"] = refs
            row["suggest_safari"] = app.suggestion(refs["safari"])
            row["suggest_share"] = app.suggestion(refs["share"])
        candidate = resolver.resolve(case["url"])
        row["resolver"] = None if candidate is None else {
            "feed": candidate.feed_url, "title": candidate.title, "confidence": candidate.confidence,
            "kind": candidate.kind, "audio_items": candidate.audio_items, "reason": candidate.reason}
        row["resolver_ok"] = (candidate.feed_url if candidate else None) == case["expect_feed"] and (
            candidate is None or candidate.confidence <= case.get("max_confidence", 1.0))
        rows.append(row)
    return rows


def _cell(result) -> str:
    if result is None:
        return "–"
    if result["ok"]:
        feeds = result["feeds"]
        return "✅ " + ", ".join(f.replace("https://", "") for f in feeds) + (" (choose)" if len(feeds) > 1 else "")
    return "❌ " + result["check"]


def markdown(rows: list) -> str:
    lines = [
        "# B2 baseline: Follow for Substack links, today vs. resolver",
        "",
        "Generated by `python3 run_cases.py --write` from recorded responses in `fixtures/`.",
        "Suggestion columns assume the item already passed the 25%-listened-or-Margin gate",
        "(`Gate1AppModel.swift:15802`). Articles never get the manual Follow button",
        "(`Gate1AppModel.swift:15670`), so that column is omitted.",
        "",
        "| Case | Following tab paste | Suggestion, Safari/Link import | Suggestion, share sheet | Resolver |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        res = r["resolver"]
        resolver = ("✅ " if r["resolver_ok"] else "❌ ") + (res["feed"].replace("https://", "") if res else "none")
        lines.append(f"| `{r['id']}` ({r['category']}) | {_cell(r['following_tab'])} | "
                     f"{_cell(r.get('suggest_safari'))} | {_cell(r.get('suggest_share'))} | {resolver} |")
    total = len(rows)
    lines += ["", f"Resolver: {sum(r['resolver_ok'] for r in rows)}/{total} cases give the expected feed "
              "(controls expect none).",
              f"Following tab today: {sum(bool(r['following_tab']['ok']) and r['following_tab']['feeds'] == [r['expect_feed']] for r in rows)}/{total} "
              "give exactly the expected feed.",
              f"Suggestion today (Safari/Link import), article items: "
              f"{sum(r['suggest_safari']['ok'] for r in rows if 'suggest_safari' in r)}/"
              f"{sum('suggest_safari' in r for r in rows)} find a feed.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    mode = "record" if "--record" in sys.argv else "replay"
    rows = run(mode)
    text = markdown(rows)
    print(text)
    if "--write" in sys.argv:
        (HERE / "results.md").write_text(text)
        (HERE / "results.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False) + "\n")
