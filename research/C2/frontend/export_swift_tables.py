"""Writes the constant tables of the Swift front end from the Python reference, so none is retyped by hand.

Run from research/C2/frontend:  python export_swift_tables.py
Output: Packages/SessionKit/Sources/SessionKitSpeechFrontEnd/FrontEndTables.swift
Needs numpy only (frontend.py imports it); no reference data and no espeak.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import frontend  # noqa: E402
import neural_g2p  # noqa: E402
import normalize  # noqa: E402
from kitten_symbols import SYMBOLS  # noqa: E402

OUT = HERE.parents[2] / "Packages" / "SessionKit" / "Sources" / "SessionKitSpeechFrontEnd" / "FrontEndTables.swift"
q = lambda s: json.dumps(s, ensure_ascii=False)


def pairs(name, items, doc):
    body = "".join(f"        ({q(k)}, {q(v)}),\n" for k, v in items)
    return f"    /// {doc}\n    static let {name}: [(String, String)] = [\n{body}    ]\n"


def table(name, mapping, doc):
    body = "".join(f"        {q(k)}: {q(v)},\n" for k, v in mapping.items())
    return f"    /// {doc}\n    static let {name}: [String: String] = [\n{body}    ]\n"


def words(name, items, doc):
    return f"    /// {doc}\n    static let {name}: [String] = [{', '.join(q(w) for w in items)}]\n"


parts = [
    "// Generated by research/C2/frontend/export_swift_tables.py from the Python reference. Don't edit by hand:\n"
    "// change the reference, regenerate, and let KittenFrontEndTests check the port against test_vectors.json.\n"
    "enum FrontEndTables {\n",
    words("ones", normalize.ONES, "Number words 0 through 19."),
    words("tens", normalize.TENS, "Tens words, indexed by tens digit (the first two entries are placeholders)."),
    "    /// Scale words with their values, largest first.\n    static let scales: [(UInt64, String)] = ["
    + ", ".join(f"({v}, {q(n)})" for v, n in normalize.SCALES) + "]\n",
    pairs("greek", normalize.GREEK.items(), "Greek letters to their names, in the reference's order."),
    pairs("units", normalize.UNITS.items(), "Units after a number, in the reference's order (the longest is tried first)."),
    pairs("shortUnits", normalize.SHORT_UNITS.items(), "One-letter units, which need a space before them."),
    f"    /// The months and abbreviations a year can follow.\n    static let months = {q(normalize.MONTHS)}\n",
    f"    /// What can introduce a year.\n    static let yearCue = {q(normalize.YEAR_CUE)}\n",
    words("alwaysSpell", sorted(normalize.ALWAYS_SPELL), "Words spelled out letter by letter."),
    table("currency", normalize.CURRENCY, "Currency symbols to their plural unit."),
    pairs("symbols", normalize.SYMBOLS.items(), "Symbols to the words they are read as, in the reference's order."),
    table("numberWords", frontend.NUMBER_WORDS, "Number words in the forms Kitten heard in training."),
    words("tensWords", sorted(frontend.TENS_WORDS), "Tens words that join a following digit word."),
    table("functionWords", frontend.FUNCTION, "Function words in reduced forms."),
    table("arpabet", frontend.ARPA, "CMUdict phones to IPA."),
    table("letterNames", frontend.LETTERS, "Letter names, for spelled-out abbreviations."),
    words("g2pGraphemes", neural_g2p.GRAPHEMES, "The neural fallback's letters, in id order."),
    words("g2pPhonemes", neural_g2p.PHONEMES, "The neural fallback's phones, in id order."),
    "    /// Kitten's symbols with their ids, as a later duplicate overwrites an earlier one.\n"
    "    static let kittenSymbols: [(UInt32, Int)] = [\n"
    + "".join(f"        ({ord(c)}, {i}),\n" for c, i in SYMBOLS.items() if len(c) == 1) + "    ]\n",
    "}\n",
]
assert all(len(c) == 1 for c in SYMBOLS), "a Kitten symbol is more than one code point"
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts), encoding="utf-8")
print(f"wrote {OUT}")
