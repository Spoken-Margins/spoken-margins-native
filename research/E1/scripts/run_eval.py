"""Score the E1 baselines on the public evaluation set (and the owner set, if labeled).

Usage: python scripts/run_eval.py [--nl-tags recorded_nl_tags.json]
Needs spaCy with en_core_web_md (see research/E1/README.md).
Writes results/<set>-<baseline>.json and results/summary.md.
"""
import argparse, functools, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import spacy
from e1eval import data, portable, score, textcat
from e1eval.spacy_full import SpacyFull
from e1eval.tagger import SpacyNLEmulator, RecordedNLTags

RESULTS = data.ROOT / "results"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--nl-tags", help="NLTagger output recorded on a Mac (swift/NLTagDump.swift)")
    ap.add_argument("--owner", help="owner set loader output (see e1eval/owner.py)", default=None)
    args = ap.parse_args()

    nlp = spacy.load("en_core_web_md")
    lemma = functools.lru_cache(maxsize=None)(lambda w: nlp(w)[0].lemma_.lower())
    emu = SpacyNLEmulator(nlp)
    nl = RecordedNLTags(args.nl_tags) if args.nl_tags else emu

    sets = {"public": data.load_public(), "heldout": data.load_heldout()}
    if args.owner:
        from e1eval import owner
        sets["owner"] = owner.load(args.owner)

    RESULTS.mkdir(exist_ok=True)
    summary = {}
    # Trained kind classifier: cross-validated on the public set, and trained on all of it
    # for any other set, so those numbers are a true transfer test.
    public_model = textcat.train(sets["public"])
    textcat_kinds = {}
    for set_name, margins in sets.items():
        pk = textcat.cross_validate(margins) if set_name == "public" else textcat.predict(public_model, margins)
        textcat_kinds[set_name] = {
            split: score.score_kind([m for m in margins if split == "all" or m.split == split], {k: {"kind": v} for k, v in pk.items()})
            for split in ("all", "dev", "test") if split == "all" or any(m.split == split for m in margins)}
    (RESULTS / "textcat-kind.json").write_text(json.dumps(textcat_kinds, indent=1))
    for set_name, margins in sets.items():
        runs = {
            "portable": portable.predict(margins, nl),
            "spacy": SpacyFull(nlp, emu).predict(margins),
        }
        for base, preds in runs.items():
            res = {"all": score.score_all(margins, preds, lemma)}
            for split in ("dev", "test"):
                sub = [m for m in margins if m.split == split]
                if sub:
                    res[split] = score.score_all(sub, preds, lemma)
            res["tagger"] = "recorded NLTagger" if (base == "portable" and args.nl_tags) else "spaCy en_core_web_md"
            summary[(set_name, base)] = res
            (RESULTS / f"{set_name}-{base}.json").write_text(json.dumps(res, indent=1))
            if set_name == "owner":
                continue  # predictions quote the owner's words; only scores are written for this set
            (RESULTS / f"{set_name}-{base}-predictions.json").write_text(
                json.dumps({m.id: preds[m.id] for m in margins}, indent=1))
    (RESULTS / "summary.md").write_text(render(summary, textcat_kinds))
    print((RESULTS / "summary.md").read_text())


def render(summary, textcat_kinds):
    lines = ["# E1 M1 baseline scores", "",
             "Generated by `scripts/run_eval.py`. Per-category numbers are on all Margins in the set;",
             "`test` is the held-out sources (rules were only tuned while looking at `dev` errors).", ""]
    for set_name in sorted({s for s, _ in summary}):
        P, S = summary[(set_name, "portable")], summary[(set_name, "spacy")]
        a = P["all"]
        lines += [f"## {set_name} set ({a['n']} Margins)", "", "| Measure | Portable | spaCy upper bound |", "|---|---|---|"]
        def row(name, f):
            vals = [f(P["all"]), f(S["all"])]
            if "test" in P:
                vals = [f"{v} (test {f(r['test'])})" for v, r in zip(vals, (P, S))]
            lines.append(f"| {name} | {vals[0]} | {vals[1]} |")
        row("Statement kind accuracy", lambda r: r["kind"]["accuracy"])
        row("Referent accuracy (exact)", lambda r: r["referent"]["accuracy"])
        row("Referent within ±1 sentence", lambda r: r["referent"]["within_one_sentence"])
        row("Entities F1 (span, any type)", lambda r: r["entities"]["any"]["f1"])
        row("Entities F1 (span and type)", lambda r: r["entities"]["typed"]["f1"])
        row("Topics F1 (head lemma)", lambda r: r["topics"]["f1"])
        tk = textcat_kinds[set_name]["all"]
        how = "4-fold CV grouped by source" if set_name == "public" else "trained on the public set"
        lines += ["", f"Trained spaCy textcat for statement kind ({how}): accuracy {tk['accuracy']}"
                  + (f" (test {textcat_kinds[set_name]['test']['accuracy']})" if "test" in textcat_kinds[set_name] else "") + "."]
        lines += ["", f"Always-anchor-sentence referent baseline: {a['referent']['anchor_sentence_baseline']}.", "",
                  "### Statement kind, per class", "", "| Kind | Portable P / R / F1 | spaCy P / R / F1 | textcat F1 |", "|---|---|---|---|"]
        for k in data.KINDS:
            p, s = P["all"]["kind"][k], S["all"]["kind"][k]
            lines.append(f"| {k} | {p['p']} / {p['r']} / {p['f1']} | {s['p']} / {s['r']} / {s['f1']} | {tk[k]['f1']} |")
        lines += ["", "### Entities, per type", "", "| Type | Portable P / R / F1 | spaCy P / R / F1 |", "|---|---|---|"]
        for t in data.ENTITY_TYPES:
            p, s = P["all"]["entities"][t], S["all"]["entities"][t]
            lines.append(f"| {t} | {p['p']} / {p['r']} / {p['f1']} | {s['p']} / {s['r']} / {s['f1']} |")
        lines += ["", "### Referent, by gold scope (correct / n)", "", "| Scope | Portable | spaCy |", "|---|---|---|"]
        for sc in P["all"]["referent"]["by_gold_scope"]:
            p, s = P["all"]["referent"]["by_gold_scope"][sc], S["all"]["referent"]["by_gold_scope"][sc]
            lines.append(f"| {sc} | {p['correct']} / {p['n']} | {s['correct']} / {s['n']} |")
        lines += ["", "### Links (P / R / F1)", "", "| Link | Portable | spaCy |", "|---|---|---|"]
        for l in P["all"]["links"]:
            p, s = P["all"]["links"][l], S["all"]["links"][l]
            lines.append(f"| {l} | {p['p']} / {p['r']} / {p['f1']} | {s['p']} / {s['r']} / {s['f1']} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    main()
