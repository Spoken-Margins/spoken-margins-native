import Foundation

/// What the first MP3 frame says about how the file is indexed (#2660).
public enum MP3FirstFrameHeader: Equatable, Sendable {
    /// A "Xing" tag: variable bit rate with a seek table.
    case xing
    /// A "VBRI" tag (Fraunhofer): variable bit rate with a seek table.
    case vbri
    /// An "Info" tag: constant bit rate that still carries the Xing layout.
    case info
    /// A Layer III frame with none of the tags, or no frame found in the bytes given.
    case none
    /// The bytes ended before the answer could be read; at least this many bytes from the start are needed.
    case needMoreData(minimumLength: Int)
}

/// Reads the first frame of an MP3 and says whether it carries a Xing or VBRI header. Pure, so it is host-tested
/// on generated bytes. Streams only ask AVFoundation for precise timing when this says VBR with a header, because
/// that is the one case where the key is cheap over HTTP and the seek is otherwise wrong (`ops/stream-seek`).
public enum MP3VBRHeaderParser {
    /// How far past the ID3 tag the parser looks for a frame start. Encoders sometimes pad with zeros.
    static let maxSyncScan = 4096

    public static func parse(_ data: Data) -> MP3FirstFrameHeader {
        let bytes = [UInt8](data)
        var offset = 0
        if bytes.starts(with: [0x49, 0x44, 0x33]) { // "ID3"
            guard bytes.count >= 10 else { return .needMoreData(minimumLength: 10) }
            let sizeBytes = bytes[6...9]
            guard sizeBytes.allSatisfy({ $0 & 0x80 == 0 }) else { return .none }
            let size = sizeBytes.reduce(0) { ($0 << 7) | Int($1) }
            let footer = bytes[5] & 0x10 != 0 ? 10 : 0
            offset = 10 + size + footer
        }
        let scanEnd = offset + maxSyncScan
        guard bytes.count > offset else { return .needMoreData(minimumLength: offset + 4096) }
        var position = offset
        while position + 4 <= bytes.count, position < scanEnd {
            if let tagOffset = tagOffset(bytes, at: position) {
                let tagStart = position + tagOffset
                let vbriStart = position + 36
                let needed = max(tagStart, vbriStart) + 4
                guard bytes.count >= needed else { return .needMoreData(minimumLength: needed) }
                switch String(decoding: bytes[tagStart..<(tagStart + 4)], as: UTF8.self) {
                case "Xing": return .xing
                case "Info": return .info
                default: break
                }
                if String(decoding: bytes[vbriStart..<(vbriStart + 4)], as: UTF8.self) == "VBRI" { return .vbri }
                return .none
            }
            position += 1
        }
        return position >= scanEnd ? .none : .needMoreData(minimumLength: min(scanEnd, bytes.count + 4096) + 4)
    }

    /// True for the headers whose files are worth the precise-timing key over HTTP.
    public static func warrantsPreciseTiming(_ header: MP3FirstFrameHeader) -> Bool {
        header == .xing || header == .vbri
    }

    /// Where the Xing/Info tag sits from the frame start, if a valid Layer III frame header is at `position`.
    private static func tagOffset(_ b: [UInt8], at position: Int) -> Int? {
        guard b[position] == 0xFF, b[position + 1] & 0xE0 == 0xE0 else { return nil }
        let versionBits = (b[position + 1] >> 3) & 0x3
        let layerBits = (b[position + 1] >> 1) & 0x3
        guard versionBits != 1, layerBits == 1 else { return nil } // reserved version; Layer III only
        let bitrateIndex = b[position + 2] >> 4
        let sampleRateIndex = (b[position + 2] >> 2) & 0x3
        guard bitrateIndex != 0x0F, bitrateIndex != 0, sampleRateIndex != 0x3 else { return nil }
        let hasCRC = b[position + 1] & 0x1 == 0
        let mono = (b[position + 3] >> 6) & 0x3 == 3
        let sideInfo = versionBits == 3 ? (mono ? 17 : 32) : (mono ? 9 : 17)
        return 4 + (hasCRC ? 2 : 0) + sideInfo
    }
}

/// Decides, per stream URL, whether to ask for precise timing, from a small ranged read of the file's start.
/// `AudioAdapters.play` builds its item synchronously, so it only consults `cachedAnswer`; the probe itself runs
/// when the episode is configured, off the main actor. Any failure, timeout or unknown answer means "no key",
/// which is how streams behaved before.
public final class MP3VBRHeaderProbe: @unchecked Sendable {
    public typealias Fetch = @Sendable (_ url: URL, _ byteCount: Int) async throws -> Data

    public static let shared = MP3VBRHeaderProbe()
    static let firstReadBytes = 4096
    static let maxReadBytes = 262_144

    private let fetch: Fetch
    private let lock = NSLock()
    private var answers: [URL: Bool] = [:]
    private var inFlight: Set<URL> = []

    public init(fetch: @escaping Fetch = MP3VBRHeaderProbe.rangedFetch(timeout: 3)) {
        self.fetch = fetch
    }

    /// The answer if the probe has finished for this URL; nil means unknown, so play without the key.
    public func cachedAnswer(for url: URL) -> Bool? {
        lock.lock(); defer { lock.unlock() }
        return answers[url]
    }

    /// Starts the probe for a network URL unless it is cached or already running. Returns at once.
    @discardableResult
    public func prefetch(_ url: URL) -> Task<Void, Never>? {
        guard let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https" else { return nil }
        guard begin(url) else { return nil }
        return Task.detached(priority: .utility) { [self] in
            let result = await probe(url)
            finish(url, result)
        }
    }

    private func begin(_ url: URL) -> Bool {
        lock.lock(); defer { lock.unlock() }
        if answers[url] != nil || inFlight.contains(url) { return false }
        inFlight.insert(url)
        return true
    }

    private func finish(_ url: URL, _ result: Bool?) {
        lock.lock(); defer { lock.unlock() }
        inFlight.remove(url)
        if let result { answers[url] = result }
    }

    /// nil when the bytes could not be read, so a later configure may try again.
    func probe(_ url: URL) async -> Bool? {
        do {
            var length = Self.firstReadBytes
            for _ in 0..<2 {
                let header = MP3VBRHeaderParser.parse(try await fetch(url, length))
                if case .needMoreData(let needed) = header {
                    guard needed <= Self.maxReadBytes, needed > length else { return false }
                    length = needed
                    continue
                }
                return MP3VBRHeaderParser.warrantsPreciseTiming(header)
            }
            return false
        } catch {
            return nil
        }
    }

    /// A `Range: bytes=0-(n-1)` read that stops after n bytes even if the server ignores the range.
    public static func rangedFetch(timeout: TimeInterval) -> Fetch {
        { url, byteCount in
            var request = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData, timeoutInterval: timeout)
            request.setValue("bytes=0-\(byteCount - 1)", forHTTPHeaderField: "Range")
            let configuration = URLSessionConfiguration.ephemeral
            configuration.timeoutIntervalForRequest = timeout
            configuration.timeoutIntervalForResource = timeout
            let session = URLSession(configuration: configuration)
            defer { session.invalidateAndCancel() }
            let (stream, response) = try await session.bytes(for: request)
            if let http = response as? HTTPURLResponse, !(200..<300).contains(http.statusCode) {
                throw URLError(.badServerResponse)
            }
            var data = Data()
            for try await byte in stream {
                data.append(byte)
                if data.count >= byteCount { break }
            }
            return data
        }
    }
}
