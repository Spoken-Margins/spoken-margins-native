#!/usr/bin/env python3
"""Flag open PRs whose body names no issue GitHub can link (#2167). Deterministic, no model, never blocks a merge.

Owner call 2026-10-19: every PR body says `Closes #N` (finishes the issue) or `Part of #N` (doesn't). Half of the
last 50 merged PRs named none, so issues were closed by hand and the board's "Linked pull requests" stayed empty.

For each open PR into the trunk:
  - the body names an issue (Closes/Fixes/Resolves #N or a URL to it, or Part of #N): nothing to do, and a
    `needs-issue-link` label from an earlier pass comes off;
  - the body says `No issue` on a line of its own, the title starts with `chore:`, or every changed file is a
    Markdown note under `ops/`: housekeeping, exempt;
  - otherwise the PR gets the `needs-issue-link` label and one comment saying what to add. The comment is posted
    once (a marker in it stops a second one when the label is removed by hand).

Dry-run is the default; --apply writes. It runs from the Claude Mac worker's hourly board pass
(ops/claude/sm_claude_worker.py), next to scripts/sm_project_sync.py, and reuses sm_status's reads.
Needs GH_TOKEN or GITHUB_TOKEN (or `gh auth token`). Exit 0 whatever it flagged; 2 when a read failed.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment_trust
import sm_status

LABEL = 'needs-issue-link'
MARKER = '<!-- needs-issue-link -->'
TARGET = r'(?:#(\d+)|https://github\.com/[\w.-]+/[\w.-]+/issues/(\d+))'   # `#12` or a URL to the issue
CLOSING = re.compile(r'\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)[ \t]*:?[ \t]+' + TARGET, re.I)   # same line, as GitHub reads it
PART_OF = re.compile(r'\bpart[ \t]+of[ \t]*:?[ \t]+' + TARGET, re.I)
NO_ISSUE = re.compile(r'^[ \t]*[*_>\- \t]*no[ \t]+issue[*_]*(?:[ \t]*[:.!—-].*)?$', re.I | re.M)   # not "No issue yet"

HOUSEKEEPING_TITLE = re.compile(r'^\s*chore(\([^)]*\))?!?:', re.I)
COMMENT = (
    f"{MARKER}\n"
    "This PR's description names no issue that GitHub can link. Please add one line to the body:\n"
    "- `Closes #N` if it finishes issue N, or\n"
    "- `Part of #N` if it doesn't, or\n"
    "- `No issue` on a line of its own, for housekeeping.\n\n"
    "A `(#N)` in the title alone doesn't link. This label comes off by itself once the body is fixed, and it never "
    "blocks the merge (#2167).\n\n"
    "---\n_Generated by [Claude Code](https://claude.ai/code)_"
)


def named_issues(pull: dict) -> list[int]:
    """The issues the body names in a form GitHub reads (or, for `Part of`, that a reader can follow). A PR can't
    name itself, so its own number never counts."""
    body = pull.get('body') or ''
    found = []
    for pattern in (CLOSING, PART_OF):
        for match in pattern.finditer(body):
            number = match.group(1) or match.group(2)
            if number and int(number) != pull.get('number'):
                found.append(int(number))
    return list(dict.fromkeys(found))


def exempt(pull: dict, files: list[str] | None = None) -> bool:
    """Housekeeping that may say `No issue` instead: it says so, a `chore:` title, or only notes under ops/."""
    if NO_ISSUE.search(pull.get('body') or '') or HOUSEKEEPING_TITLE.match(pull.get('title') or ''):
        return True
    return bool(files) and all(name.startswith('ops/') and name.endswith('.md') for name in files)


def reconcile(api, apply: bool = False) -> dict:
    report = {'apply': apply, 'flagged': [], 'cleared': [], 'unchanged': 0, 'unknown': []}
    pulls = api.pages(f'pulls?state=open&base={sm_status.BASE}&sort=created&direction=asc')
    for pull in pulls:
        number = pull['number']
        has_label = any(label['name'] == LABEL for label in pull.get('labels') or [])
        try:
            if named_issues(pull) or exempt(pull):
                clean = True
            else:
                files = [f['filename'] for f in api.pages(f'pulls/{number}/files')]
                clean = exempt(pull, files)
            if clean and not has_label:
                report['unchanged'] += 1
            elif clean:
                report['cleared'].append(number)
                if apply:
                    try:
                        api.delete(f'issues/{number}/labels/{LABEL}')
                    except sm_status.GitHubError as error:
                        if 'HTTP 404' not in str(error):   # 404: someone took the label off first
                            raise
            elif has_label:
                report['unchanged'] += 1
            else:
                report['flagged'].append(number)
                if apply:
                    # Comment first, label last: the label means "already told", so a failure in between retries.
                    seen = comment_trust.trusted_only(api.pages(f'issues/{number}/comments'))
                    if not any(MARKER in (c.get('body') or '') for c in seen):
                        api.post(f'issues/{number}/comments', {'body': COMMENT})
                    api.post(f'issues/{number}/labels', {'labels': [LABEL]})
        except (sm_status.GitHubError, KeyError, TypeError, ValueError, OSError) as error:
            report['unknown'].append({'pr': number, 'reason': str(error)})
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--repo', default=sm_status.REPO)
    args = parser.parse_args(argv)
    try:
        report = reconcile(sm_status.GitHub(args.repo), args.apply)
    except sm_status.GitHubError as error:
        print(json.dumps({'unknown': [{'pr': None, 'reason': str(error)}]}, indent=2))
        return 2
    print(json.dumps(report, indent=2))
    return 2 if report['unknown'] else 0


if __name__ == '__main__':
    sys.exit(main())
