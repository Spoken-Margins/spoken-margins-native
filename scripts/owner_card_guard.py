#!/usr/bin/env python3
"""Keep the owner's queue honest (#3898). Deterministic, no model. Dry-run by default; --apply writes.

The owner does not read issue comments, so a card posted there is not delivered unless the label says so, and a
label with no card gives him nothing to answer. For each open issue (scripts/sm_owner_queue.py reads them):
  - `needs-owner` and no card: one comment (marker below) tells the thread to write the card; flagged "card_missing".
    An issue that also carries `needs-design` is the design routine's (#3866): not judged here.
  - a live card (`**Decision for Cole**` / `**Step for Cole**` from a trusted author) and no `needs-owner`: the
    label is added; flagged "labelled".
  - a card ended by `<!-- owner-answered -->` while `needs-owner` is still on: flagged "answered_label_on", for a
    thread to clear.
Prose such as "the owner's call" is never auto-labelled (34 of 84 such matches were false, #3898). A stranger's
card or marker is data (scripts/comment_trust.py). Runs hourly from ops/claude/sm_claude_worker.py, next to
scripts/ready_owner_only.py. Exit 0 whatever it flagged; 2 when a read or write failed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment_trust
import sm_owner_queue as queue
import sm_status

MISSING_MARKER = '<!-- owner-card-missing -->'
MISSING_COMMENT = (
    f"{MISSING_MARKER}\n"
    "This issue has `needs-owner` but no card the owner can answer, and he does not read issue comments. Post a "
    "comment that starts with `**Decision for Cole**` (or `**Step for Cole**` for something only he can do on his "
    "accounts or machines): what this is in one sentence, the question, your pick, the other options with their "
    "cost, and what it blocks. `scripts/sm_owner_queue.py` then prints it for him. If this is a taste, wording or "
    "layout call, it is the design pass's: use `needs-design` and take `needs-owner` off.\n\n"
    "---\n_Generated by [Claude Code](https://claude.ai/code)_"
)


def already_told(issue: dict) -> bool:
    """Whether a trusted comment carries the missing-card marker (a stranger's does not stop the reminder)."""
    return any(MISSING_MARKER in (c.get('body') or '') for c in comment_trust.trusted_only(issue.get('comments')))


def reconcile(api, issues: list[dict], apply: bool = False) -> dict:
    report = {'apply': apply, 'card_missing': [], 'labelled': [], 'answered_label_on': [], 'unknown': []}
    for issue in sorted(issues, key=lambda i: i['number']):
        number, labels = issue['number'], set(issue.get('labels') or [])
        card = queue.newest_card(issue)
        try:
            if card and not card['answered']:
                if queue.NEEDS_OWNER not in labels:
                    report['labelled'].append(number)
                    if apply:
                        api.post(f'issues/{number}/labels', {'labels': [queue.NEEDS_OWNER]})
            elif queue.NEEDS_OWNER in labels and card:
                report['answered_label_on'].append(number)
            elif queue.NEEDS_OWNER in labels and queue.NEEDS_DESIGN not in labels:
                report['card_missing'].append(number)
                if apply and not already_told(issue):
                    api.post(f'issues/{number}/comments', {'body': MISSING_COMMENT})
        except (sm_status.GitHubError, KeyError, TypeError, ValueError, OSError) as error:
            report['unknown'].append({'issue': number, 'reason': str(error)})
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--repo', default=sm_status.REPO)
    args = parser.parse_args(argv)
    try:
        api = sm_status.GitHub(args.repo)
        report = reconcile(api, queue.fetch_issues(api), args.apply)
    except (sm_status.GitHubError, KeyError, TypeError) as error:
        print(json.dumps({'unknown': [{'issue': None, 'reason': str(error)}]}, indent=2))
        return 2
    print(json.dumps(report, indent=2))
    return 2 if report['unknown'] else 0


if __name__ == '__main__':
    sys.exit(main())
