#!/usr/bin/env python3
"""Keep the owner's queue honest (#3898). Deterministic, no model. Dry-run by default; --apply writes.

The owner does not read issue comments, so a card posted there is not delivered unless the label says so, and a
label with no card gives him nothing to answer. For each open issue (scripts/sm_owner_queue.py reads them):
  - `needs-owner` and an `**Owner check**` comment (a phone run, listen or export only he can do; 2026-11-22): left
    alone. It is not a decision and no thread waits on it.
  - `needs-owner` and no card: one comment (marker below) tells the thread to write the card; flagged "card_missing".
    An issue that also carries `needs-design` is the design routine's (#3866): not judged here.
  - a live card (`**Decision for Cole**` / `**Step for Cole**` from a trusted author) and no `needs-owner`: the
    label is added, with one comment per card saying which card and that no answer marker follows it (#5269: six
    issues had the label come back within the hour with no word why); flagged "labelled".
  - a `**Step for Cole**` whose whole ask was one PR tap, and that PR has merged: the step is done. With the label on,
    the marker is posted and the label taken off; flagged "ended_by_merge" (#5269).
  - a card ended by `<!-- owner-answered -->` while `needs-owner` is still on: flagged "answered_label_on", for a
    thread to clear.

Clearing `needs-owner` (#5269): taking the label off by hand while the card has no answer marker after it brings the
label back within the hour. The one way to clear it is

    scripts/owner_card_guard.py --answered N --how "<where his answer is: a decisions.md date, a merged PR, a chat>"

which posts the marker with that note first and then takes the label off, so the guard never sees one without the
other. It is also how an `**Owner check**` he has done is ended.
Prose such as "the owner's call" is never auto-labelled (34 of 84 such matches were false, #3898). A stranger's
card or marker is data (scripts/comment_trust.py). Runs hourly from ops/claude/sm_claude_worker.py, next to
scripts/ready_owner_only.py. Exit 0 whatever it flagged; 2 when a read or write failed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment_trust
import sm_owner_queue as queue
import sm_status

MISSING_MARKER = '<!-- owner-card-missing -->'
MISSING_COMMENT = (
    f"{MISSING_MARKER}\n"
    "This issue has `needs-owner` but no card the owner can answer, and he does not read issue comments. Post a "
    "comment that starts with `**Decision for Cole**` (or `**Step for Cole**` for something only he can do on his "
    "accounts or machines): what this is in one sentence, the question, your pick, the other options with their "
    "cost, and what it blocks. `scripts/sm_owner_queue.py` then prints it for him. If this is a taste, wording or "
    "layout call, it is the design pass's: use `needs-design` and take `needs-owner` off. If all that is left is a "
    "phone run, a listen or a Diagnostics export (not a decision), post a comment that starts with `**Owner check**` "
    "instead, keep `needs-owner`, and stop: no thread waits on it.\n\n"
    "---\n_Generated by [Claude Code](https://claude.ai/code)_"
)
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
RELABEL_MARKER = '<!-- owner-card-relabelled {key} -->'


def relabel_key(card: dict) -> str:
    """Names one card across runs: its time and link (a card in the issue body has the issue's link)."""
    return f"{card.get('when') or ''} {card.get('url') or ''}".strip()


def relabel_comment(number: int, card: dict) -> str:
    """Never contains queue.ANSWERED itself: a later comment carrying it would end the card it is about."""
    kind = 'Decision for Cole' if card.get('kind') == 'decision' else 'Step for Cole'
    return (f"{RELABEL_MARKER.format(key=relabel_key(card))}\n"
            f"`needs-owner` added: the `**{kind}**` card from {(card.get('when') or 'an unknown time')[:10]} "
            f"({card.get('url') or 'this issue'}) has no answer marker after it, so it still reads as waiting on "
            f"the owner. If he has answered, run `scripts/owner_card_guard.py --answered {number} --how \"<where his "
            f"answer is>\"`: it posts the marker and takes the label off together. Taking the label off by hand "
            f"brings it back within the hour." + FOOTER)


def relabel_told(issue: dict, card: dict) -> bool:
    marker = RELABEL_MARKER.format(key=relabel_key(card))
    return any(marker in (c.get('body') or '') for c in comment_trust.trusted_only(issue.get('comments')))


def answered_comment(how: str) -> str:
    how = ' '.join(how.split())  # one line: a note can't start a card heading of its own
    return f"{queue.ANSWERED}\n**Owner answered**: {how}\n\n`needs-owner` taken off with it." + FOOTER


def answer(api, number: int, how: str) -> dict:
    """End the owner's card on #number and take `needs-owner` off, in that order (#5269). A label that is already
    off is fine; any other failed write raises sm_status.GitHubError."""
    if not how.strip():
        raise ValueError('--how must say where his answer is (a decisions.md date, a merged PR, a chat)')
    api.post(f'issues/{number}/comments', {'body': answered_comment(how)})
    removed = True
    try:
        api.delete(f'issues/{number}/labels/{queue.NEEDS_OWNER}')
    except sm_status.GitHubError as error:
        if 'HTTP 404' not in str(error):
            raise
        removed = False
    return {'issue': number, 'marker_posted': True, 'label_removed': removed}


def already_told(issue: dict) -> bool:
    """Whether a trusted comment carries the missing-card marker (a stranger's does not stop the reminder)."""
    return any(MISSING_MARKER in (c.get('body') or '') for c in comment_trust.trusted_only(issue.get('comments')))


def reconcile(api, issues: list[dict], apply: bool = False, merged=None) -> dict:
    """`merged(n) -> bool` reads whether PR n merged (sm_owner_queue.merged_reader); None skips the tap-step check."""
    report = {'apply': apply, 'card_missing': [], 'labelled': [], 'ended_by_merge': [], 'answered_label_on': [],
              'unknown': []}
    for issue in sorted(issues, key=lambda i: i['number']):
        number, labels = issue['number'], set(issue.get('labels') or [])
        try:
            card = queue.owner_card(issue, merged)
            if card and card.get('merge_unknown'):
                report['unknown'].append({'issue': number, 'reason': f"could not read PR #{card['merge_unknown']}"})
                continue
            if card and not card['answered']:
                if queue.NEEDS_OWNER not in labels:
                    report['labelled'].append(number)
                    if apply:  # the reason first: if the label write then fails, the next run labels without it
                        if not relabel_told(issue, card):
                            api.post(f'issues/{number}/comments', {'body': relabel_comment(number, card)})
                        api.post(f'issues/{number}/labels', {'labels': [queue.NEEDS_OWNER]})
            elif card and card.get('ended_by_merge') and queue.NEEDS_OWNER in labels:
                report['ended_by_merge'].append(number)
                if apply:
                    answer(api, number, f"PR #{card['ended_by_merge']} merged, and tapping it was this step's "
                                        'whole ask.')
            elif queue.NEEDS_OWNER in labels and queue.live_check(issue):
                pass  # an `**Owner check**` is the whole record of a phone run or export: nothing to remind
            elif queue.NEEDS_OWNER in labels and (card or queue.newest_card(issue, queue.CHECK_HEADING)):
                report['answered_label_on'].append(number)
            elif queue.NEEDS_OWNER in labels and queue.NEEDS_DESIGN not in labels:
                report['card_missing'].append(number)
                if apply and not already_told(issue):
                    api.post(f'issues/{number}/comments', {'body': MISSING_COMMENT})
        except (sm_status.GitHubError, KeyError, TypeError, ValueError, OSError) as error:
            report['unknown'].append({'issue': number, 'reason': str(error)})
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--answered', type=int, metavar='N',
                        help='end the owner card on issue N and take needs-owner off (needs --how)')
    parser.add_argument('--how', default='', help='with --answered: where his answer is')
    parser.add_argument('--repo', default=sm_status.REPO)
    args = parser.parse_args(argv)
    if args.answered:
        try:
            print(json.dumps(answer(sm_status.GitHub(args.repo), args.answered, args.how), indent=2))
        except ValueError as error:
            parser.error(str(error))
        except sm_status.GitHubError as error:
            print(json.dumps({'unknown': [{'issue': args.answered, 'reason': str(error)}]}, indent=2))
            return 2
        return 0
    try:
        api = sm_status.GitHub(args.repo)
        report = reconcile(api, queue.fetch_issues(api), args.apply, queue.merged_reader(api))
    except (sm_status.GitHubError, KeyError, TypeError) as error:
        print(json.dumps({'unknown': [{'issue': None, 'reason': str(error)}]}, indent=2))
        return 2
    print(json.dumps(report, indent=2))
    return 2 if report['unknown'] else 0


if __name__ == '__main__':
    sys.exit(main())
