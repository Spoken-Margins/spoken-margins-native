#!/usr/bin/env python3
"""Builds and checks the voice catalog's draft and fixtures (#1816).

  voice_catalog_tools.py draft      rewrite the Supertonic draft catalog from its asset-manifest.json
  voice_catalog_tools.py fixtures   rewrite the signed fixtures in Contracts/fixtures/voice-model-catalog/
                                    (needs the `cryptography` package; the output is deterministic)

`scripts/validate-contracts.py` imports `check_draft_matches_manifest` and `check_envelope_payloads`,
which need no signing library. The fixtures are signed with a published test key, so nothing here is
a secret: the production signing key is generated by the owner and never enters this repository.
"""

