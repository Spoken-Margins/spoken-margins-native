def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def pretty(value) -> bytes:
    return (json.dumps(value, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


# --- the Supertonic draft ------------------------------------------------------------------------

def _license_file_hash(name: str) -> str:
    return sha256_hex((SUPERTONIC / "licenses" / name).read_bytes())


def build_supertonic_draft() -> dict:
    manifest = json.loads((SUPERTONIC / "asset-manifest.json").read_text(encoding="utf-8"))
    revision = manifest["modelRevision"]
    licenses = [
        {
            "id": "supertonic-model-openrail-m",
            "name": "BigScience Open RAIL-M License (Supertonic 3 model)",
            "textURL": f"{HF_BASE}{revision}/LICENSE",
            "textSHA256": _license_file_hash("SUPERTONIC_MODEL_OPENRAIL-M.txt"),
            "requiresAcceptance": True,
            "restrictionsSummary": RAIL_SUMMARY,
        },
        {
            "id": "supertonic-code-mit",
            "name": "MIT License (Supertonic code)",
            "spdxId": "MIT",
            "textURL": "https://raw.githubusercontent.com/supertone-inc/supertonic/main/LICENSE",
            "textSHA256": _license_file_hash("SUPERTONIC_CODE_MIT.txt"),
            "requiresAcceptance": False,
        },
        {
            "id": "onnxruntime-mit",
            "name": "MIT License (ONNX Runtime)",
            "spdxId": "MIT",
            "textURL": "https://raw.githubusercontent.com/microsoft/onnxruntime/v1.24.2/LICENSE",
            "textSHA256": _license_file_hash("ONNXRUNTIME_MIT.txt"),
            "requiresAcceptance": False,
        },
        {
            "id": "sherpa-onnx-apache-2-0",
            "name": "Apache License 2.0 (sherpa-onnx INT8 build)",
            "spdxId": "Apache-2.0",
            "textURL": "https://www.apache.org/licenses/LICENSE-2.0.txt",
            "textSHA256": _license_file_hash("SHERPA_ONNX_APACHE-2.0.txt"),
            "requiresAcceptance": False,
        },
    ]
    license_for_provenance = {
        "sherpaInt8Archive": "supertonic-model-openrail-m",
        "supertonicModel": "supertonic-model-openrail-m",
        "supertonicCodeLicense": "supertonic-code-mit",
        "onnxRuntime": "onnxruntime-mit",
        "sherpaAttribution": "sherpa-onnx-apache-2-0",
    }
    license_file_ids = {
        "licenses/SUPERTONIC_MODEL_OPENRAIL-M.txt": "supertonic-model-openrail-m",
        "licenses/SUPERTONIC_CODE_MIT.txt": "supertonic-code-mit",
        "licenses/ONNXRUNTIME_MIT.txt": "onnxruntime-mit",
        "licenses/SHERPA_ONNX_APACHE-2.0.txt": "sherpa-onnx-apache-2-0",
    }

    files = []
    for entry in manifest["files"]:
        path, provenance = entry["path"], entry["provenance"]
        file = {"path": path, "byteCount": entry["bytes"], "sha256": entry["sha256"]}
        if provenance == "localNotice":
            # Our own short text, which no publisher serves: the catalog carries it.
            file["content"] = (SUPERTONIC / path).read_text(encoding="utf-8")
        elif provenance == "supertonicModel":
            # The pinned upstream revision serves these bytes as they are.
            upstream_path = "LICENSE" if path == "licenses/SUPERTONIC_MODEL_OPENRAIL-M.txt" else path
            file["sources"] = [f"{HF_BASE}{revision}/{upstream_path}"]
        elif provenance == "sherpaInt8Archive":
            file["sources"] = [SHERPA_INT8_BASE + path.rsplit("/", 1)[-1].replace(".onnx", ".int8.onnx")]
        else:
            file["sources"] = [LICENSE_FILE_SOURCES[path]]
        license_id = license_file_ids.get(path) or license_for_provenance.get(provenance)
        if license_id and provenance != "localNotice":
            file["licenseId"] = license_id
        files.append(file)

    return {
        "schemaVersion": "voice-model-catalog.v1",
        "catalogVersion": 1,
        "issuedAt": "2026-10-17T00:00:00Z",
        "voices": [
            {
                "id": "supertonic-3-int8",
                "displayName": "Supertonic 3",
                "publisher": "Supertone Inc. (INT8 build by k2-fsa/sherpa-onnx)",
                "version": f"{revision[:7]}+int8-2026-05-11",
                "runtime": {"name": "onnxruntime", "version": "1.24.2"},
                "minimumIOSVersion": "26.0",
                # Placeholder: iOS 26 runs on phones with 4 GB, so this adds no limit beyond the OS
                # until the footprint is measured on a device.
                "minimumMemoryMegabytes": 4096,
                "status": "available",
                "bundled": False,
                "files": files,
                "licenses": licenses,
            }
        ],
    }


def check_draft_matches_manifest() -> list[str]:
    """The draft's files are exactly the Supertonic files the manifest lists, by path, size and SHA-256.

    Those are the files the app bundled until #1820. scripts/validate-supertonic-assets.py holds the kept
    files to their bytes, and this holds the draft to the manifest: audio already rendered with the bundled
    voice stays valid once it downloads.
    """
    errors: list[str] = []
    manifest = json.loads((SUPERTONIC / "asset-manifest.json").read_text(encoding="utf-8"))
    expected = {e["path"]: (e["bytes"], e["sha256"]) for e in manifest["files"]}
    draft = json.loads(DRAFT.read_text(encoding="utf-8"))
    voice = next((v for v in draft["voices"] if v["id"] == "supertonic-3-int8"), None)
    if voice is None:
        return [f"{DRAFT}: no supertonic-3-int8 voice"]
    actual = {f["path"]: (f["byteCount"], f["sha256"]) for f in voice["files"]}
    for path in sorted(expected.keys() - actual.keys()):
        errors.append(f"{DRAFT}: {path} is bundled but missing from the draft")
    for path in sorted(actual.keys() - expected.keys()):
        errors.append(f"{DRAFT}: {path} is in the draft but not bundled")
    for path in sorted(expected.keys() & actual.keys()):
        if expected[path] != actual[path]:
            errors.append(f"{DRAFT}: {path} size or sha256 differs from asset-manifest.json")
    if build_supertonic_draft() != draft:
        errors.append(f"{DRAFT}: out of date; run scripts/voice_catalog_tools.py draft")
    return errors


def check_envelope_payloads() -> list[str]:
    """Each envelope-<name>.json carries exactly the bytes of catalog-<name>.json (except bad-signature)."""
    errors: list[str] = []
    for envelope_path in sorted(FIXTURES.glob("envelope-*.json")):
        name = envelope_path.stem.removeprefix("envelope-")
        if name == "bad-signature":
            continue
        catalog_path = FIXTURES / f"catalog-{name}.json"
        if not catalog_path.is_file():
            errors.append(f"{envelope_path}: no {catalog_path.name} beside it")
            continue
        payload = base64.b64decode(json.loads(envelope_path.read_text(encoding="utf-8"))["payload"])
        if payload != catalog_path.read_bytes():
            errors.append(f"{envelope_path}: payload differs from {catalog_path.name}; run scripts/voice_catalog_tools.py fixtures")
    return errors


