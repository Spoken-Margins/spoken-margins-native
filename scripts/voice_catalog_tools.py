def fixture_catalogs() -> dict[str, dict]:
    valid_voices = [_fixture_bundled_voice(), _fixture_voice()]
    old = _fixture_voice()
    old.update({"id": "fixture-voice-old", "version": "0.9", "status": "withdrawn"})
    older = _fixture_voice()
    older.update({"id": "fixture-voice-older", "version": "0.5", "status": "superseded", "supersededBy": "fixture-voice"})
    future = _fixture_voice()
    future.update({"id": "fixture-future-runtime", "runtime": {"name": "coreml", "version": "9.0"}})
    return {
        "valid": _catalog(3, valid_voices),
        "withdrawn": _catalog(4, valid_voices + [old, older]),
        "unknown-runtime": _catalog(3, valid_voices + [future]),
        # Properly signed, but 1 is lower than the 3 the tests say was accepted before.
        "rollback": _catalog(1, [_fixture_voice()]),
        "unknown-key": _catalog(3, valid_voices),
        "archive": _catalog(5, valid_voices + [_fixture_archive_voice()]),
    }


def _key(label: bytes):
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    return Ed25519PrivateKey.from_private_bytes(hashlib.sha256(label).digest())


def _public_b64(private_key) -> str:
    from cryptography.hazmat.primitives import serialization

    raw = private_key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return base64.b64encode(raw).decode()


def sign_envelope(key_id: str, private_key, payload: bytes) -> dict:
    return {
        "schemaVersion": "voice-model-catalog-envelope.v1",
        "keyId": key_id,
        "algorithm": "ed25519",
        "payload": base64.b64encode(payload).decode(),
        "signature": base64.b64encode(private_key.sign(SIGNING_CONTEXT + payload)).decode(),
    }


def write_fixtures() -> None:
    FIXTURES.mkdir(parents=True, exist_ok=True)
    test_key = _key(b"spoken-margins voice-model-catalog test key")
    other_key = _key(b"spoken-margins voice-model-catalog other key")
    (FIXTURES / "test-keys.json").write_bytes(pretty({
        "note": "Public halves of the keys the fixtures are signed with. Test keys only: their private halves are derived in scripts/voice_catalog_tools.py and sign nothing real.",
        "trusted": {"keyId": TEST_KEY_ID, "publicKey": _public_b64(test_key)},
        "untrusted": {"keyId": OTHER_KEY_ID, "publicKey": _public_b64(other_key)},
    }))
    catalogs = fixture_catalogs()
    for name, catalog in catalogs.items():
        payload = pretty(catalog)
        (FIXTURES / f"catalog-{name}.json").write_bytes(payload)
        signer, key_id = (other_key, OTHER_KEY_ID) if name == "unknown-key" else (test_key, TEST_KEY_ID)
        (FIXTURES / f"envelope-{name}.json").write_bytes(pretty(sign_envelope(key_id, signer, payload)))
    # A signature over the valid catalog attached to a payload someone edited afterwards.
    signed = sign_envelope(TEST_KEY_ID, test_key, pretty(catalogs["valid"]))
    tampered = json.loads(json.dumps(catalogs["valid"]))
    tampered["voices"][1]["files"][0]["sha256"] = "0" * 64
    signed["payload"] = base64.b64encode(pretty(tampered)).decode()
    (FIXTURES / "envelope-bad-signature.json").write_bytes(pretty(signed))
    # Invalid envelopes: the schema must reject each (Contracts/fixtures/invalid/voice-model-catalog/).
    invalid = ROOT / "Contracts/fixtures/invalid/voice-model-catalog"
    invalid.mkdir(parents=True, exist_ok=True)
    good = sign_envelope(TEST_KEY_ID, test_key, pretty(catalogs["valid"]))
    no_signature = {k: v for k, v in good.items() if k != "signature"}
    (invalid / "envelope-missing-signature.json").write_bytes(pretty(no_signature))
    (invalid / "envelope-wrong-algorithm.json").write_bytes(pretty({**good, "algorithm": "rsa"}))
    (invalid / "envelope-short-signature.json").write_bytes(pretty({**good, "signature": good["signature"][:-4]}))
    # Invalid catalogs: a file must name exactly one place its bytes come from (#2086).
    payloads = ROOT / "Contracts/fixtures/invalid/voice-model-catalog-payload"
    payloads.mkdir(parents=True, exist_ok=True)
    two_places = json.loads(json.dumps(catalogs["archive"]))
    two_places["voices"][2]["files"][0]["sources"] = ["https://models.example.org/fixture-voice/1.0/model.onnx"]
    (payloads / "catalog-file-with-two-places.json").write_bytes(pretty(two_places))
    no_place = json.loads(json.dumps(catalogs["valid"]))
    del no_place["voices"][1]["files"][0]["sources"]
    (payloads / "catalog-file-with-no-place.json").write_bytes(pretty(no_place))


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in ("draft", "fixtures"):
        print(__doc__, file=sys.stderr)
        return 2
    if argv[1] == "draft":
        FIXTURES.mkdir(parents=True, exist_ok=True)
        DRAFT.write_bytes(pretty(build_supertonic_draft()))
    else:
        write_fixtures()
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
