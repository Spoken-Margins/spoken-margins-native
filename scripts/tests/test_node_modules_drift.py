"""scripts/node_modules_drift.py: a moved lockfile says `npm ci`, not "bundle is stale" (#2569)."""
import json
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(SCRIPTS))
import node_modules_drift as drift  # noqa: E402


def checkout(locked, installed):
    """A temporary checkout whose lockfile and node_modules/.package-lock.json hold these packages."""
    root = Path(tempfile.mkdtemp())
    self_packages = {'': {'name': 'x'}, **locked}
    (root / 'package-lock.json').write_text(json.dumps({'packages': self_packages}))
    if installed is not None:
        (root / 'node_modules').mkdir()
        (root / 'node_modules' / '.package-lock.json').write_text(json.dumps({'packages': installed}))
    return root


class Drift(unittest.TestCase):
    def test_table(self):
        defuddle = 'node_modules/defuddle'
        rows = [
            ('same version', {defuddle: {'version': '0.19.5'}}, {defuddle: {'version': '0.19.5'}}, []),
            ('lock moved on (the #2552 case)', {defuddle: {'version': '0.19.5'}}, {defuddle: {'version': '0.19.4'}},
             ['defuddle: installed 0.19.4, lock wants 0.19.5']),
            ('new package never installed', {defuddle: {'version': '1.0.0'}}, {}, ['defuddle: not installed, lock wants 1.0.0']),
            ('other-platform optional package', {'node_modules/@esbuild/aix-ppc64': {'version': '1', 'optional': True}}, {}, []),
            ('scoped name', {'node_modules/@xmldom/xmldom': {'version': '2'}}, {'node_modules/@xmldom/xmldom': {'version': '1'}},
             ['@xmldom/xmldom: installed 1, lock wants 2']),
            ('nested copy', {'node_modules/a/node_modules/b': {'version': '2'}}, {'node_modules/a/node_modules/b': {'version': '1'}},
             ['b: installed 1, lock wants 2']),
            ('linked workspace', {'packages/w': {'link': True}}, {}, []),
            ('extra installed package', {}, {defuddle: {'version': '1'}}, []),
        ]
        for name, locked, installed, expected in rows:
            with self.subTest(name):
                self.assertEqual(drift.drift(checkout(locked, installed)), expected)

    def test_no_install_record_is_not_drift(self):
        self.assertEqual(drift.drift(checkout({'node_modules/a': {'version': '1'}}, None)), [])

    def test_message_names_the_fix_and_caps_the_list(self):
        text = drift.message([f'p{i}: installed 1, lock wants 2' for i in range(8)])
        self.assertIn('npm ci', text)
        self.assertIn('and 3 more', text)
        self.assertNotIn('p7', text)


if __name__ == '__main__':
    unittest.main()
