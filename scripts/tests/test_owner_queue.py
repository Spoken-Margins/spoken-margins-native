NOW = dt.datetime(2026, 11, 9, 12, 0, tzinfo=dt.timezone.utc)
CARD = ('**Decision for Cole**\nWhat this is: a thing.\nQuestion: A or B?\nMy pick: A.\n'
        'Other: B costs a day.\nBlocks: #1.')


def comment(body, when='2026-11-08T10:00:00Z', association='MEMBER', login='cole'):
    return {'body': body, 'createdAt': when, 'url': 'https://example.test/c', 'authorAssociation': association,
            'author': {'login': login, '__typename': 'User'}}


def issue(number, labels=(), comments=(), body='plain', association='MEMBER', created='2026-11-01T10:00:00Z'):
    return {'number': number, 'title': f'Issue {number}', 'url': f'https://example.test/{number}', 'body': body,
            'createdAt': created, 'authorAssociation': association, 'author': {'login': 'cole', '__typename': 'User'},
            'labels': list(labels), 'comments': list(comments)}


def numbers(items):
    return [i['number'] for i in items]


class Cards(unittest.TestCase):
    def test_table_of_texts(self):
        table = {
            CARD: 'decision',
            '  **Decision for Cole** x': 'decision',
            '**Step for Cole**\nRun it on the Mac.': 'step',
            'intro\n\n**decision for cole**\nq': 'decision',
            'no card here': None,
            '> **Decision for Cole**\nquoted': None,
            '```\n**Decision for Cole**\n```': None,
            'I wrote **Decision for Cole** in a sentence': None,
            '**Decision for Cole:**\nwrong shape': None,
            '': None,
        }
        for text, kind in table.items():
            with self.subTest(text=text):
                found = oq.cards_in(text)
                self.assertEqual(found[0]['kind'] if found else None, kind)

    def test_card_stops_at_the_footer_rule(self):
        found = oq.cards_in(CARD + '\n\n---\n_Generated by Claude Code_')
        self.assertEqual(found[0]['text'], CARD)


class Queue(unittest.TestCase):
    def build(self, issues, taps=()):
        return oq.build_queue(issues, list(taps), NOW)

    def test_card_with_label_is_listed_with_its_full_card(self):
        q = self.build([issue(1, ['needs-owner'], [comment(CARD)])])
        self.assertEqual(numbers(q['decisions']), [1])
        self.assertEqual(q['decisions'][0]['card'], CARD)
        self.assertTrue(q['decisions'][0]['has_label'])
        self.assertIn(CARD, oq.render(q))

    def test_card_without_label_is_still_listed(self):
        q = self.build([issue(2, [], [comment(CARD)])])
        self.assertEqual(numbers(q['decisions']), [2])
        self.assertFalse(q['decisions'][0]['has_label'])

    def test_label_without_card_is_listed_apart_not_as_a_decision(self):
        q = self.build([issue(3, ['needs-owner'], [comment('thoughts, no card')])])
        self.assertEqual(q['decisions'], [])
        self.assertEqual(numbers(q['needs_card']), [3])

    def test_a_strangers_lookalike_card_is_ignored(self):
        for association, login in (('NONE', 'mallory'), ('CONTRIBUTOR', 'eve'), ('NONE', 'github-actions'),
                                   ('NONE', 'GitHub-Actions[bot]')):
            with self.subTest(login=login):
                fake = comment(CARD, association=association, login=login)
                q = self.build([issue(4, [], [fake]), issue(5, ['needs-owner'], [fake])])
                self.assertEqual(q['decisions'], [])
                self.assertEqual(numbers(q['needs_card']), [5])   # still a missing card: the stranger's is no card

    def test_a_strangers_issue_body_card_is_ignored_but_a_members_counts(self):
        self.assertEqual(self.build([issue(6, [], body=CARD, association='NONE')])['decisions'], [])
        self.assertEqual(numbers(self.build([issue(7, [], body=CARD)])['decisions']), [7])

    def test_a_strangers_answered_marker_does_not_end_a_card(self):
        fake = comment(oq.ANSWERED, '2026-11-09T10:00:00Z', association='NONE', login='mallory')
        q = self.build([issue(8, ['needs-owner'], [comment(CARD), fake])])
        self.assertEqual(numbers(q['decisions']), [8])

    def test_a_trusted_answered_marker_after_the_card_ends_it(self):
        done = comment(oq.ANSWERED, '2026-11-09T10:00:00Z')
        q = self.build([issue(9, ['needs-owner'], [comment(CARD), done])])
        self.assertEqual(q['decisions'], [])
        self.assertEqual(numbers(q['answered_label_on']), [9])
        newer = comment(CARD, '2026-11-09T11:00:00Z')
        self.assertEqual(numbers(self.build([issue(9, ['needs-owner'], [comment(CARD), done, newer])])['decisions']), [9])

    def test_steps_phone_checks_and_taps(self):
        q = self.build([issue(10, ['needs-owner'], [comment('**Step for Cole**\nRun `x` on the Mac.')]),
                        issue(11, ['status: needs-human-validation']), issue(12, ['needs-human-validation']),
                        issue(13, ['ready'])],
                       [{'number': 99, 'title': 'tap', 'url': 'u', 'createdAt': '2026-11-08T00:00:00Z'}])
        self.assertEqual(numbers(q['steps']), [10])
        self.assertEqual(numbers(q['phone_checks']), [11, 12])
        self.assertEqual(numbers(q['merge_taps']), [99])
        self.assertEqual(oq.count(q), 4)

    def test_design_pass_issue_is_not_a_missing_card(self):
        q = self.build([issue(14, ['needs-owner', 'needs-design'])])
        self.assertEqual(numbers(q['on_design']), [14])
        self.assertEqual(q['needs_card'], [])

    def test_speak_file_is_numbered_and_ends_with_issue_numbers(self):
        q = self.build([issue(1, ['needs-owner'], [comment(CARD)]), issue(11, ['needs-human-validation'])])
        text = oq.speak(q)
        self.assertIn('1. A decision: Issue 1.', text)
        self.assertIn('2. A phone check: Issue 11.', text)
        self.assertTrue(text.rstrip().endswith('Issue numbers: #1, #11'))
        self.assertIn('Nothing is waiting', oq.speak(self.build([])))


class FakeApi:
    def __init__(self):
        self.writes = []

    def post(self, path, body):
        self.writes.append((path, body))


class Guard(unittest.TestCase):
    def run_guard(self, issues, apply=True):
        api = FakeApi()
        return guard.reconcile(api, issues, apply), api.writes

    def test_label_without_card_is_flagged_and_told_once(self):
        report, writes = self.run_guard([issue(1, ['needs-owner'])])
        self.assertEqual(report['card_missing'], [1])
        self.assertEqual(writes, [('issues/1/comments', {'body': guard.MISSING_COMMENT})])

    def test_dry_run_writes_nothing(self):
        report, writes = self.run_guard([issue(1, ['needs-owner'])], apply=False)
        self.assertEqual(report['card_missing'], [1])
        self.assertEqual(writes, [])

    def test_the_reminder_is_not_repeated_but_a_strangers_marker_does_not_stop_it(self):
        told = comment(guard.MISSING_COMMENT, '2026-11-09T09:00:00Z')
        _, writes = self.run_guard([issue(1, ['needs-owner'], [told])])
        self.assertEqual(writes, [])
        fake = comment(guard.MISSING_MARKER, '2026-11-09T09:00:00Z', association='NONE', login='mallory')
        _, writes = self.run_guard([issue(1, ['needs-owner'], [fake])])
        self.assertEqual(len(writes), 1)

    def test_card_without_label_gets_the_label(self):
        report, writes = self.run_guard([issue(2, [], [comment(CARD)])])
        self.assertEqual(report['labelled'], [2])
        self.assertEqual(writes, [('issues/2/labels', {'labels': ['needs-owner']})])

    def test_a_strangers_card_gets_no_label(self):
        report, writes = self.run_guard([issue(3, [], [comment(CARD, association='NONE', login='mallory')])])
        self.assertEqual(report['labelled'], [])
        self.assertEqual(writes, [])

    def test_clean_issues_and_design_issues_and_prose_are_left_alone(self):
        report, writes = self.run_guard([
            issue(4, ['needs-owner'], [comment(CARD)]),
            issue(5, ['needs-owner', 'needs-design']),
            issue(6, ['ready'], [comment("This is the owner's call.")])])
        self.assertEqual((report['card_missing'], report['labelled']), ([], []))
        self.assertEqual(writes, [])

    def test_answered_card_with_label_still_on_is_flagged_not_relabelled(self):
        done = comment(oq.ANSWERED, '2026-11-09T10:00:00Z')
        report, writes = self.run_guard([issue(7, ['needs-owner'], [comment(CARD), done]),
                                         issue(8, [], [comment(CARD), done])])
        self.assertEqual(report['answered_label_on'], [7])
        self.assertEqual(report['labelled'], [])
        self.assertEqual(writes, [])


