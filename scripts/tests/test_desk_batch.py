def comment(identifier, issue, body, created, login='uncomposed'):
    return {'id': identifier, 'issue_url': f'https://api.github.com/repos/o/r/issues/{issue}', 'body': body,
            'created_at': created, 'html_url': f'https://github.com/o/r/issues/{issue}#issuecomment-{identifier}',
            'user': {'login': login}, 'author_association': 'NONE' if login.endswith('[bot]') else 'OWNER'}


class FakeGitHub:
    def __init__(self, comments, pulls):
        self.comments, self.pulls, self.paths = comments, pulls, []

    def get(self, path):
        self.paths.append(path)
        if path.startswith('issues/comments?'):
            page = int(re.search(r'[?&]page=(\d+)', path).group(1))
            return self.comments[(page - 1) * 100:page * 100]
        match = re.fullmatch(r'(pulls|issues)/(\d+)', path)
        if match and match.group(1) == 'pulls' and int(match.group(2)) in self.pulls:
            return self.pulls[int(match.group(2))]
        raise RuntimeError(f'not found: {path}')


def pull(title, state='open', merged=False, head='aaaaaaa1111111', labels=()):
    return {'title': title, 'state': state, 'merged_at': '2026-10-13T12:00:00Z' if merged else None,
            'head': {'sha': head}, 'labels': [{'name': name} for name in labels]}


def check(number, target, steps, created='2026-10-13T10:00:00Z', labels=()):
    return {'number': number, 'target': target, 'steps': steps, 'created': created, 'labels': list(labels),
            'stamp': (created, number)}


class ParsingTests(unittest.TestCase):
    def test_request_fields(self):
        request = desk.parse_request(REQUEST_1551)
        self.assertEqual(request['commit'], '3997dbbe')
        self.assertIn('Run the app test classes above', request['scenario'])
        self.assertIn('3. On Now, tap the passage', request['scenario'])
        self.assertTrue(request['watch for'].startswith('the dock'))
        self.assertNotIn('watch for', request['scenario'])

    def test_fenced_request_and_footer(self):
        request = desk.parse_request('```text\n' + REQUEST_335 + '```\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_')
        self.assertEqual(request['commit'], 'bb007253')
        self.assertNotIn('Generated', request['scenario'])

    def test_other_comments_are_not_requests(self):
        for body in ('/lane T3\ncommit: abc1234\ntests: X', '/lane T5\ncommit: abc1234', 'T4 please',
                     'We could /lane T4 this', '', 'Lane report t4-1 — PASS'):
            self.assertIsNone(desk.parse_request(body), body)

    def test_request_spelling(self):
        self.assertIsNotNone(desk.parse_request('  /LANE   t4\ncommit: abc1234'))
        self.assertEqual(desk.parse_request('/lane T4')['commit'], '')

    def test_desk_reports_count_and_runner_reports_do_not(self):
        self.assertTrue(desk.is_desk_report(DESK_REPORT))
        self.assertTrue(desk.is_desk_report('```text\nLane report t4-1122-bb00725 — FAIL at step 2\n```'))
        self.assertTrue(desk.is_desk_report('**Lane report desk-9 - INCONCLUSIVE**'))
        # as the desks of 2026-10-13 wrote them on #644 and #1523
        self.assertTrue(desk.is_desk_report('**Lane report (T4): FAIL · PR #644 (#336) · build bb007253 · Test Desk, 2026-10-13**\n\nSimulator'))
        self.assertTrue(desk.is_desk_report('**Lane report (T4): PASS · PR #1523 (#997, J3 and J5) · build bb007253**'))
        for body in (RUNNER_REPORT, 'Lane report pr723-r37247546869-auto — PASS', 'Lane report integration-4622b1a — PASS',
                     'Test Desk T4 hand-off, build bb007253: #335 not run', 'Lane report t4-1 — MAYBE', 'Lane report (T4)', 'Lane report\nPASS', ''):
            self.assertFalse(desk.is_desk_report(body), body)

    def test_prose_and_odd_words_in_a_desk_report_do_not_change_what_it_is(self):
        # a half-done check's hand-off must not answer it; "journeys-" in the title is not a runner id
        self.assertFalse(desk.is_desk_report('Lane report t4-5-abc — hand-off: J3 pass, J5 not run'))
        self.assertFalse(desk.is_desk_report('Lane report t4-1 — in progress; will fail if not fixed'))
        self.assertTrue(desk.is_desk_report('**Lane report (T4): FAIL · PR #644 journeys-batch fix**'))
        self.assertTrue(desk.is_desk_report('Lane report t4-1 — PASS (integration-test of share)'))

    def test_journey_steps_counts_numbered_top_level_steps(self):
        with tempfile.TemporaryDirectory() as tmp:
            (Path(tmp) / 'docs').mkdir()
            (Path(tmp) / 'docs' / 'journeys.md').write_text(
                '# Journeys\n1. not under a journey\n\n'
                '## J1 \u2014 First\n\n1. one\n   - Pass: nested bullet\n2. two\n   1. nested number\n3. three\n4. four\n\n'
                '## Notes\n\n1. not a journey\n\n'
                '## J10 \u2014 Tenth\n\n1. only\n', encoding='utf-8')
            self.assertEqual(desk.journey_steps(tmp), {'J1': 4, 'J10': 1})
        self.assertEqual(desk.journey_steps(SCRIPTS.parent / 'nowhere'), {})

    def test_journey_steps_reads_the_real_journeys_doc(self):
        # The doc grows as journeys gain steps (J1 went from 3 to 4 in #1579), so pin the shape, not the counts.
        steps = desk.journey_steps(SCRIPTS.parent)
        self.assertTrue({'J1', 'J2', 'J3'} <= set(steps))
        self.assertTrue(all(count >= 1 for count in steps.values()), steps)

    def test_step_units(self):
        journeys = {'J3': 4, 'J5': 6}
        self.assertEqual(desk.step_units(desk.parse_request(REQUEST_1551), journeys), 3)
        self.assertEqual(desk.step_units({'run': 'J3, J5'}, journeys), 10)
        self.assertEqual(desk.step_units({'run': 'J9'}, journeys), desk.DEFAULT_JOURNEY_STEPS)
        self.assertEqual(desk.step_units({}, journeys), desk.DEFAULT_CHECK_STEPS)
        self.assertEqual(desk.step_units({'scenario': '1. one'}, journeys), 2)


class PendingTests(unittest.TestCase):
    def pending(self, *comments):
        return desk.pending_requests(list(comments), {})

    def test_unanswered_request_is_pending(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'))
        self.assertEqual([r['number'] for r in found], [335])
        self.assertEqual(found[0]['steps'], 3)

    def test_runner_report_does_not_answer_a_request(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'),
                             comment(2, 335, RUNNER_REPORT, '2026-10-13T13:30:00Z', 'github-actions[bot]'))
        self.assertEqual([r['number'] for r in found], [335])

    def test_handoff_does_not_answer_a_request(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'),
                             comment(2, 335, 'Test Desk T4 hand-off: #335 PASS in progress', '2026-10-13T13:45:00Z'))
        self.assertEqual([r['number'] for r in found], [335])

    def test_desk_report_answers_it(self):
        self.assertEqual(self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'),
                                      comment(2, 335, DESK_REPORT, '2026-10-13T13:45:00Z')), [])

    def test_report_for_another_pr_does_not(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'),
                             comment(2, 644, DESK_REPORT, '2026-10-13T13:45:00Z'))
        self.assertEqual([r['number'] for r in found], [335])

    def test_a_report_before_the_request_does_not_answer_it(self):
        found = self.pending(comment(2, 335, DESK_REPORT, '2026-10-13T13:00:00Z'),
                             comment(1, 335, REQUEST_335, '2026-10-13T13:17:00Z'))
        self.assertEqual([r['number'] for r in found], [335])

    def test_a_new_request_after_a_report_is_pending_again(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:00:00Z'),
                             comment(2, 335, DESK_REPORT, '2026-10-13T13:45:00Z'),
                             comment(3, 335, REQUEST_1551, '2026-10-13T18:00:00Z'))
        self.assertEqual([(r['number'], r['commit']) for r in found], [(335, '3997dbbe')])

    def test_the_newest_request_on_a_pr_replaces_older_ones(self):
        found = self.pending(comment(1, 335, REQUEST_335, '2026-10-13T13:00:00Z'),
                             comment(3, 335, REQUEST_1551, '2026-10-13T18:00:00Z'))
        self.assertEqual([r['commit'] for r in found], ['3997dbbe'])


class DescribeTests(unittest.TestCase):
    def describe(self, pulls, *numbers):
        requests = [dict(desk.parse_request(REQUEST_335), number=n, stamp=('2026-10-13T10:00:00Z', n),
                         created='2026-10-13T10:00:00Z', steps=3) for n in numbers]
