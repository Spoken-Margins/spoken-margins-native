class BatchTests(unittest.TestCase):
    def test_checks_that_share_a_build_batch_together(self):
        batches = desk.make_batches([check(1, 'next tip', 5), check(2, 'abc1234', 5), check(3, 'next tip', 5)])
        self.assertEqual([(b['target'], [c['number'] for c in b['checks']]) for b in batches],
                         [('next tip', [1, 3]), ('abc1234', [2])])

    def test_budget_splits_a_group(self):
        batches = desk.make_batches([check(n, 'next tip', 10, f'2026-10-13T1{n}:00:00Z') for n in range(1, 5)], budget=24)
        self.assertEqual([[c['number'] for c in b['checks']] for b in batches], [[1, 2], [3, 4]])
        self.assertEqual([b['steps'] for b in batches], [20, 20])

    def test_check_cap_splits_a_group(self):
        batches = desk.make_batches([check(n, 'next tip', 2, f'2026-10-13T0{n}:00:00Z') for n in range(1, 7)], max_checks=4)
        self.assertEqual([len(b['checks']) for b in batches], [4, 2])

    def test_one_oversize_check_gets_its_own_batch(self):
        batches = desk.make_batches([check(1, 'next tip', 40), check(2, 'next tip', 3, '2026-10-13T11:00:00Z')], budget=24)
        self.assertEqual([[c['number'] for c in b['checks']] for b in batches], [[1], [2]])

    def test_priority_then_oldest(self):
        batches = desk.make_batches([check(1, 'a', 3, '2026-10-13T01:00:00Z'), check(2, 'b', 3, '2026-10-13T09:00:00Z', ['priority']),
                                     check(3, 'c', 3, '2026-10-13T00:00:00Z')])
        self.assertEqual([b['target'] for b in batches], ['b', 'c', 'a'])

    def test_nothing_pending_makes_no_batches(self):
        self.assertEqual(desk.make_batches([]), [])


class DecisionTests(unittest.TestCase):
    def verdict(self, checks, **options):
        return desk.decide(desk.make_batches(checks), NOW, **options)

    def test_a_lone_priority_check_does_not_hide_a_ready_batch(self):
        checks = [check(1, 'abc1234', 2, '2026-10-13T19:00:00Z', ['priority'])] + \
                 [check(n, 'next tip', 6, '2026-10-13T19:00:00Z') for n in (2, 3, 4, 5)]
        batches = desk.make_batches(checks)
        self.assertEqual(batches[0]['target'], 'abc1234')
        go, why = desk.decide(batches, NOW)
        self.assertTrue(go, why)
        self.assertEqual(batches[0]['target'], 'next tip')

    def test_nothing_waiting(self):
        self.assertEqual(desk.decide([], NOW), (False, 'no unanswered /lane T4 requests'))

    def test_three_checks_go(self):
        go, why = self.verdict([check(n, 'next tip', 2, '2026-10-13T19:00:00Z') for n in (1, 2, 3)])
        self.assertTrue(go, why)
        self.assertTrue(why.startswith('GO: 3 checks'))

    def test_twelve_steps_go(self):
        go, why = self.verdict([check(1, 'next tip', 8, '2026-10-13T19:00:00Z'), check(2, 'next tip', 4, '2026-10-13T19:00:00Z')])
        self.assertTrue(go, why)
        self.assertIn('12 steps', why)

    def test_a_long_wait_goes(self):
        go, why = self.verdict([check(1, 'next tip', 3, '2026-10-13T13:00:00Z')])
        self.assertTrue(go, why)
        self.assertIn('waited past 6 h', why)

    def test_a_small_recent_batch_stops_and_says_what_it_waits_for(self):
        go, why = self.verdict([check(1, 'next tip', 3, '2026-10-13T19:00:00Z'), check(2, 'next tip', 3, '2026-10-13T19:30:00Z')])
        self.assertFalse(go)
        self.assertEqual(why, 'STOP: 2 checks, 6 steps, oldest waiting 1 h; waiting for 3 checks, 12 steps, or 6 h')

    def test_force_goes_anyway_and_thresholds_can_change(self):
        small = [check(1, 'next tip', 3, '2026-10-13T19:00:00Z')]
        self.assertTrue(self.verdict(small, force=True)[0])
        self.assertTrue(self.verdict(small, min_checks=1)[0])


class MainTests(unittest.TestCase):
    def run_main(self, api, *args):
        out, err = io.StringIO(), io.StringIO()
        with tempfile.TemporaryDirectory() as folder, contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = desk.main(['--out-dir', folder, *args], api=api, now=NOW)
            files = sorted(path.name for path in Path(folder).iterdir())
            latest = (Path(folder) / 'latest.md').read_text() if 'latest.md' in files else ''
        return code, out.getvalue(), err.getvalue(), files, latest

    def api(self, count=3):
        comments = [comment(10 + n, 100 + n, REQUEST_335, f'2026-10-13T1{n}:00:00Z') for n in range(count)]
        pulls = {100 + n: pull(f'Fix {n}', 'closed', True) for n in range(count)}
        return FakeGitHub(comments, pulls)

    def test_go_writes_the_work_list(self):
        code, out, _, files, latest = self.run_main(self.api(3), '--print')
        self.assertEqual(code, 0)
        self.assertTrue(out.startswith('GO: 3 checks'))
        self.assertEqual(len(files), 2)
        self.assertIn('latest.md', files)
        for text in (latest, out):
            self.assertIn("the trunk's tip", text)
            self.assertIn('## 1. PR #100: Fix 0', text)
            self.assertIn('## 3. PR #102: Fix 2', text)
            self.assertIn('Import the outline test PDF', text)

    def test_stop_writes_nothing(self):
        api = self.api(2)
        api.comments = [comment(10, 100, REQUEST_335, '2026-10-13T19:00:00Z')]
        code, out, _, files, _ = self.run_main(api)
        self.assertEqual(code, 1)
        self.assertTrue(out.startswith('STOP: 1 check, 3 steps'))
        self.assertEqual(files, [])

    def test_force_writes_even_on_stop(self):
        api = self.api(1)
        code, _, _, files, latest = self.run_main(api, '--force')
        self.assertIn('latest.md', files)
        self.assertEqual(code, 0)

    def test_nothing_pending(self):
        code, out, _, files, _ = self.run_main(FakeGitHub([], {}))
        self.assertEqual((code, files), (1, []))
        self.assertIn('no unanswered', out)

    def test_github_error_is_exit_2_and_never_a_go(self):
        class Down:
            def get(self, path):
                raise RuntimeError('gh api: no route to host')
        code, out, err, files, _ = self.run_main(Down())
        self.assertEqual((code, out, files), (2, '', []))
        self.assertIn('ERROR: RuntimeError: gh api: no route to host', err)

    def test_a_failure_after_go_is_exit_2_not_stop(self):
        out, err = io.StringIO(), io.StringIO()
        with tempfile.TemporaryDirectory() as folder, contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            blocker = Path(folder) / 'file'
            blocker.write_text('')
            code = desk.main(['--out-dir', str(blocker / 'sub')], api=self.api(3), now=NOW)
        self.assertEqual(code, 2)
        self.assertIn('ERROR:', err.getvalue())

    def test_comments_are_read_page_by_page(self):
        comments = [comment(1000 + n, 5, 'chatter', '2026-10-13T09:00:00Z') for n in range(150)]
        comments.append(comment(5000, 335, REQUEST_335, '2026-10-13T10:00:00Z'))
        api = FakeGitHub(comments, {335: pull('Chapter number', 'closed', True)})
        found = desk.comments_since(api, '2026-10-03T20:00:00Z')
        self.assertEqual(len(found), 151)
        self.assertEqual(len([p for p in api.paths if p.startswith('issues/comments?')]), 2)

    def test_a_strangers_t4_request_never_reaches_the_planner(self):
        """#1822: the Test Desk runs journeys on the owner's Mac for whoever asks, so a stranger can't ask."""
        forged = dict(comment(6000, 335, REQUEST_335, '2026-10-13T10:00:00Z', login='mallory'), author_association='NONE')
        owner = comment(6001, 336, REQUEST_335, '2026-10-13T10:05:00Z')
        api = FakeGitHub([forged, owner], {})
        found = desk.comments_since(api, '2026-10-03T20:00:00Z')
        self.assertEqual([c['id'] for c in found], [6001])
        self.assertEqual(sorted(request['number'] for request in desk.pending_requests(found, {})), [336])

    def test_json_plan(self):
        code, out, _, files, _ = self.run_main(self.api(3), '--json')
        self.assertEqual((code, files), (0, []))
        self.assertIn('"number": 100', out)


