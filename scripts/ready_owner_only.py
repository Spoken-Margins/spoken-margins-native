#!/usr/bin/env python3
"""Take `ready` off an issue whose only work left is the owner's own check (#3666). Deterministic, no model.

Owner call 2026-11-07, on #3109 and #3110, which waited two days because #3108 stayed open on his phone check:
"Absolutely no clue why that would prevent us from building out the rest of the features." The owner's check on a
slice never holds the next slice, and an issue with only his check left has no work for a thread. A `ready` label
on it sends a thread to an issue it can only hand back, and keeps the check off his phone plans, which list
`status: needs-human-validation` issues.

For each open issue (pull requests are skipped) that carries `ready`, the newest comment from a trusted author
(scripts/comment_trust.py: a stranger's comment is data and is skipped, whatever it says) is read:
  - it says "owner only", or names only the owner's check as what is left: `ready` comes off, the issue gets
    `status: needs-human-validation` (unless it already carries a validation label) and one comment saying why;
  - anything else, including an issue with no comment: nothing happens.

The comment carries a marker. When the newest trusted comment is that comment, the guard has already acted and
stays out, so an owner who puts `ready` back is never overruled in a loop; a new trusted comment makes the issue
eligible again.

Dry-run is the default; --apply writes. It runs from the Claude Mac worker's hourly pass
(ops/claude/sm_claude_worker.py), next to scripts/area_labels.py. Exit 0 whatever it flagged; 2 when a read failed.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment_trust
import sm_status

READY = 'ready'
VALIDATION = 'status: needs-human-validation'
VALIDATION_LABELS = {VALIDATION, 'needs-human-validation'}
MARKER = '<!-- ready-owner-only -->'

COMMENT = (
    f"{MARKER}\n"
    "The newest comment says only the owner's check is left, so there is no work here for a thread. `ready` comes "
    "off and the issue carries `status: needs-human-validation`, which puts the check on the owner's phone plan. "
    "It does not hold any slice that builds on this one: those are `ready` as soon as the code they build on is "
    "merged (#3666).\n\n"
    "If more work is left, say so in a new comment and put `ready` back; this check reads only the newest comment "
    "from a trusted author.\n\n"
    "---\n_Generated by [Claude Code](https://claude.ai/code)_"
)

_OWNER = r"(?:the[ \t]+)?(?:owner|his)(?:'s|\u2019s|s')?"
_CHECK = r"(?:(?:phone|device|listening)[ \t]+)?(?:check|validation|verification|pass|try|test|trial)"
_LEFT = r"(?:left|remain(?:s|ing)?|outstanding|to[ \t]+do|still[ \t]+open)"
_IS = r"(?:is[ \t]+|are[ \t]+)?"
_THATS = r"(?:that(?:'s|\u2019s|[ \t]+is)[ \t]+)?"

# Each pattern is one way a comment says "nothing is left but the owner". They are matched case-insensitively on
# one line at a time, after the body's code spans and quoted lines are removed (quoting is not a statement).
PATTERNS = (
    re.compile(r"\bowner[ \t]*[-\u2011\u2013]?[ \t]*only\b", re.I),
    re.compile(rf"\bonly[ \t]+{_OWNER}[ \t]+{_CHECK}[ \t]+{_IS}(?:what(?:'s|\u2019s|[ \t]+is)[ \t]+)?{_LEFT}\b", re.I),
    re.compile(rf"\b(?:all|everything)[ \t]+{_THATS}{_LEFT}[ \t]+is[ \t]+{_OWNER}[ \t]+{_CHECK}\b", re.I),
    re.compile(rf"\b(?:nothing|no[ \t]+work)[ \t]+{_LEFT}[ \t]+(?:but|except|besides|apart[ \t]+from)[ \t]+{_OWNER}[ \t]+{_CHECK}\b", re.I),
    re.compile(rf"\b{_OWNER}[ \t]+{_CHECK}[ \t]+is[ \t]+(?:all|the[ \t]+only[ \t]+(?:thing|step|item))[ \t]+{_THATS}{_LEFT}\b", re.I),
    re.compile(rf"\b(?:waiting|waits)[ \t]+(?:only|just)[ \t]+(?:on|for)[ \t]+{_OWNER}[ \t]+{_CHECK}\b", re.I),
    re.compile(rf"\b(?:only|just)[ \t]+(?:waiting|waits)[ \t]+(?:on|for)[ \t]+{_OWNER}[ \t]+{_CHECK}\b", re.I),
)
# "not owner only", "isn't only the owner's check left": a negation right before the match turns it round.
NEGATED = re.compile(r"(?:\bnot|\bno[ \t]+longer|\bnever|n't|n\u2019t)[ \t]+(?:just[ \t]+)?$", re.I)
CODE_SPAN = re.compile(r"```.*?```|`[^`\n]*`", re.S)
QUOTE_LINE = re.compile(r"^[ \t]*>")


def says_owner_only(body: str | None) -> bool:
    """Whether a comment says the owner's check is all that is left. Quoted lines and code spans don't count."""
    text = CODE_SPAN.sub(' ', body or '')
    for line in text.splitlines():
        if QUOTE_LINE.match(line):
            continue
        for pattern in PATTERNS:
            for match in pattern.finditer(line):
                if not NEGATED.search(line[:match.start()]):
                    return True
    return False


def newest_trusted(comments: list[dict]) -> dict | None:
    """The newest comment whose author we may believe, by creation time (GitHub lists oldest first)."""
    seen = comment_trust.trusted_only(comments)
    return max(seen, key=lambda c: c.get('created_at') or '', default=None) if seen else None


def verdict(issue: dict, comments: list[dict]) -> str | None:
    """'flag' when the issue is `ready` and its newest trusted comment names only the owner's check; else None."""
    if READY not in {label.get('name') for label in issue.get('labels') or []}:
        return None
    last = newest_trusted(comments)
    if last is None or MARKER in (last.get('body') or ''):
        return None
    return 'flag' if says_owner_only(last.get('body')) else None


def reconcile(api, apply: bool = False) -> dict:
    report = {'apply': apply, 'flagged': [], 'unchanged': 0, 'unknown': []}
    for issue in api.pages(f'issues?state=open&labels={READY}&sort=created&direction=asc', limit=10):
        if 'pull_request' in issue:
            continue
        number = issue['number']
        try:
            comments = api.pages(f'issues/{number}/comments')
            if verdict(issue, comments) is None:
                report['unchanged'] += 1
                continue
            report['flagged'].append(number)
            if apply:
                # Comment first, labels last: a failure in between retries on the next pass, and the marker keeps
                # that retry from posting twice (the guard stays out once its own comment is the newest).
                api.post(f'issues/{number}/comments', {'body': COMMENT})
                if not VALIDATION_LABELS & {label.get('name') for label in issue.get('labels') or []}:
                    api.post(f'issues/{number}/labels', {'labels': [VALIDATION]})
                try:
                    api.delete(f'issues/{number}/labels/{READY}')
                except sm_status.GitHubError as error:
                    if 'HTTP 404' not in str(error):   # 404: someone took `ready` off first
                        raise
        except (sm_status.GitHubError, KeyError, TypeError, ValueError, OSError) as error:
            report['unknown'].append({'issue': number, 'reason': str(error)})
    return report


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--apply', action='store_true')
    parser.add_argument('--repo', default=sm_status.REPO)
    args = parser.parse_args(argv)
    try:
        report = reconcile(sm_status.GitHub(args.repo), args.apply)
    except (sm_status.GitHubError, KeyError, TypeError) as error:
        print(json.dumps({'unknown': [{'issue': None, 'reason': str(error)}]}, indent=2))
        return 2
    print(json.dumps(report, indent=2))
    return 2 if report['unknown'] else 0


if __name__ == '__main__':
    sys.exit(main())
