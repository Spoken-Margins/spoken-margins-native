#!/usr/bin/env python3
"""Batch the unanswered `/lane T4` requests into work lists for the Test Desk (#1557). Stdlib, Python 3.9+.

Usage:
  scripts/desk-batch.py                 GO or STOP; on GO, write the first batch's work list
  scripts/desk-batch.py --print         also print the first batch's work list
  scripts/desk-batch.py --force         write the work list even when STOP (a desk was started by hand)
  scripts/desk-batch.py --json          print the whole plan as JSON and write nothing

Exit codes: 0 GO, 1 STOP (nothing worth a desk yet), 2 error (GitHub unreachable; nothing written).

A T4 request is a `/lane T4` comment on a PR (test-lane.md, Request format). It is answered by a
later comment on the same PR whose first line starts "Lane report" and says PASS, FAIL or INCONCLUSIVE
(`Lane report t4-… — PASS`, `Lane report (T4): FAIL · …`), unless it is the runner's (ids like `pr<PR>-r<run>`). A newer request on the same PR replaces an older one.
Hand-offs and "in progress" notes don't answer anything, so a check a desk left half done stays on the list.

How the list is built:
- Closed-unmerged PRs drop out. A merged PR's check runs on the trunk's tip; an open PR's on its head.
  Checks that share a build go in the same batch, so the desk builds and installs once.
- Cost per check is its steps: the numbered lines of `scenario:`, plus the steps of each journey in
  `run:` (counted from docs/journeys.md). The Test Desks of 2026-10-13 got through 1 to 3 checks each
  before the 250k-token line, at about 2.5k tokens per screenshot with two screenshots a step, so a
  batch holds about 24 steps and at most 4 checks. A check bigger than that gets a batch of its own.
- `priority` PRs first, then oldest first.
- GO when the first batch has 3 checks or 12 steps, or its oldest request has waited 6 hours.
  Otherwise STOP and say what it is waiting for.

The script only reads GitHub. It posts and labels nothing, and keeps no state: what is pending is
re-derived from the comments each run, so a hand-off needs no bookkeeping. Who starts a desk, and
when, is not decided here.

Environment (tests): SM_DESK_GH (the gh command, default gh), SM_DESK_REPO, SM_DESK_OUT (the folder
the work lists go to, default ~/SpokenMarginsOps/desk-batches).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import comment_trust  # noqa: E402  (#1822: a stranger's /lane T4 request is not a request)

ROOT = Path(__file__).resolve().parents[1]
REPO = os.environ.get('SM_DESK_REPO', 'Spoken-Margins/spoken-margins-native')
GH = shlex.split(os.environ.get('SM_DESK_GH', 'gh'))
OUT_DIR = Path(os.environ.get('SM_DESK_OUT') or Path.home() / 'SpokenMarginsOps' / 'desk-batches')

BUDGET = 24
MAX_CHECKS = 4
MIN_CHECKS = 3
MIN_UNITS = 12
MAX_WAIT_HOURS = 6.0
WINDOW_DAYS = 10
DEFAULT_JOURNEY_STEPS = 8
DEFAULT_CHECK_STEPS = 4
NEXT_TIP = 'next tip'

REQUEST = re.compile(r'\s*/lane\s+T4\b', re.I)
# `Lane report <id> — PASS` or `Lane report (T4): FAIL`; the verdict is upper case, so prose doesn't count
REPORT = re.compile(r'(?i:Lane report)\s+(?:\(T[45]\):?|(\S+)\s+[—–:-]+)\s*(?:PASS|FAIL|INCONCLUSIVE)\b')
RUNNER_ID = re.compile(r'(pr\d+-r\d+|integration-|journeys-)', re.I)
FIELD = re.compile(r'(commit|changed|run|tests|scenario|watch for|not needed):\s*(.*)', re.I)
NUMBERED = re.compile(r'\s*\d+[.)]\s+\S')


def parse_time(value):
    return dt.datetime.fromisoformat(value.replace('Z', '+00:00'))


def strip_fence(body):
    lines = (body or '').strip().splitlines()
    if lines and lines[0].startswith('```'):
        lines = lines[1:]
    text = '\n'.join(lines)
    return re.split(r'\n---\n_Generated by', text)[0].rstrip('`\n ')


def first_line(body):
    text = strip_fence(body)
    return next((line.strip().strip('* #') for line in text.splitlines() if line.strip()), '')


def parse_request(body):
    """The fields of a `/lane T4` comment, or None when the comment isn't one."""
    text = strip_fence(body)
    if not REQUEST.match(text.splitlines()[0] if text else ''):
        return None
    fields, current = {}, None
    for line in text.splitlines()[1:]:
        match = FIELD.fullmatch(line.strip()) if not line.startswith((' ', '\t')) else None
        if match:
            current = match.group(1).lower()
            fields[current] = match.group(2)
        elif current:
            fields[current] += '\n' + line
    fields['commit'] = (re.match(r'[0-9a-f]{7,40}', fields.get('commit', '').strip(), re.I) or [''])[0].lower()
    return {key: value.strip() for key, value in fields.items()}


def is_desk_report(body):
    match = REPORT.match(first_line(body))
    return bool(match) and not RUNNER_ID.match(match.group(1) or '')


def journey_steps(root=ROOT):
    """{'J3': 4, ...} counted from docs/journeys.md: the numbered top-level steps under each `## Jn`."""
    steps, current = {}, None
    try:
        text = (Path(root) / 'docs' / 'journeys.md').read_text(encoding='utf-8')
    except OSError:
        return steps
    for line in text.splitlines():
        heading = re.match(r'##\s+(J\d+)\b', line)
        if heading:
            current = heading.group(1).upper()
            steps[current] = 0
        elif line.startswith('## '):
            current = None
        elif current and re.match(r'\d+\.\s', line):
            steps[current] += 1
    return steps


def step_units(request, journeys):
    scenario = request.get('scenario', '')
    units = sum(1 for line in scenario.splitlines() if NUMBERED.match(line))
    for name in re.findall(r'\bJ\d+\b', request.get('run', ''), re.I):
        units += journeys.get(name.upper()) or DEFAULT_JOURNEY_STEPS
    return max(units or DEFAULT_CHECK_STEPS, 2)


class GitHub:
    def __init__(self, repo=REPO, gh=GH):
        self.repo, self.gh = repo, gh

    def get(self, path):
        done = subprocess.run(self.gh + ['api', f'repos/{self.repo}/{path}'], capture_output=True, text=True, timeout=120)
        if done.returncode:
            raise RuntimeError(f'gh api {path}: {done.stderr.strip() or done.returncode}')
        return json.loads(done.stdout)


def comments_since(api, since):
    """Every issue/PR comment since `since`, oldest first. Paged by hand: gh's own paging breaks behind the proxy."""
    found, page = [], 1
    while page <= 300:
        chunk = api.get(f'issues/comments?since={since}&sort=created&direction=asc&per_page=100&page={page}')
        found += chunk
        if len(chunk) < 100:
            return comment_trust.trusted_only(found)
        page += 1
    raise RuntimeError('more than 30000 comments in the window; shorten --window-days')


def pending_requests(comments, journeys):
    """The newest unanswered T4 request on each issue/PR."""
    by_issue = {}
    for comment in comments:
        number = int(comment['issue_url'].rsplit('/', 1)[-1])
        stamp = (comment['created_at'], int(comment['id']))
        request = parse_request(comment['body'])
        if request:
            by_issue.setdefault(number, {'request': None, 'answered': None})
            by_issue[number]['request'] = dict(request, number=number, stamp=stamp, url=comment['html_url'],
                                               created=comment['created_at'], body=strip_fence(comment['body']),
                                               author=(comment.get('user') or {}).get('login', ''))
        elif is_desk_report(comment['body']) and number in by_issue:
            by_issue[number]['answered'] = stamp
    found = []
    for entry in by_issue.values():
        request = entry['request']
        if request and not (entry['answered'] and entry['answered'] > request['stamp']):
            request['steps'] = step_units(request, journeys)
            found.append(request)
    return found


def describe(api, requests):
    """Add each request's PR facts. Returns (usable checks, [(number, why dropped)])."""
    usable, dropped = [], []
    for request in requests:
        number = request['number']
        try:
            item = api.get(f'pulls/{number}')
            merged = bool(item.get('merged_at') or item.get('merged'))
            head = (item.get('head') or {}).get('sha', '')
        except RuntimeError:
            try:
                item = api.get(f'issues/{number}')
            except RuntimeError:
                dropped.append((number, 'not found'))
                continue
            merged, head = bool((item.get('pull_request') or {}).get('merged_at')), ''
        request.update(title=item.get('title', ''), merged=merged, state=item.get('state', ''),
                       labels=[label['name'] for label in item.get('labels', [])], head=head)
        if request['state'] != 'open' and not merged:
            dropped.append((number, 'closed without merging'))
            continue
        request['target'] = NEXT_TIP if merged else (head[:7] or request['commit'][:7] or 'unknown')
        named = request['commit'][:7]
        request['note'] = ''
        if merged and named:
            request['note'] = f'the request names {named}; test the trunk\'s tip'
        elif head and named and not head.startswith(named):
            request['note'] = f'the request names {named} but the PR head is now {head[:7]}; test the head'
        usable.append(request)
    return usable, dropped


def order_key(request):
    return ('priority' not in request['labels'], request['stamp'])


def make_batches(checks, budget=BUDGET, max_checks=MAX_CHECKS):
    groups = {}
    for check in sorted(checks, key=order_key):
        groups.setdefault(check['target'], []).append(check)
    batches = []
    for target, members in groups.items():
        current = []
        for check in members:
            if current and (sum(c['steps'] for c in current) + check['steps'] > budget or len(current) >= max_checks):
                batches.append({'target': target, 'checks': current})
                current = []
            current.append(check)
        batches.append({'target': target, 'checks': current})
    for batch in batches:
        batch['steps'] = sum(c['steps'] for c in batch['checks'])
    return sorted(batches, key=lambda batch: order_key(batch['checks'][0]))


def judge(batch, now, min_checks, min_units, max_wait):
    checks, units = len(batch['checks']), batch['steps']
    waited = max((now - parse_time(c['created'])).total_seconds() for c in batch['checks']) / 3600
    facts = f'{checks} check{"s" * (checks != 1)}, {units} steps, oldest waiting {waited:.0f} h'
    if checks >= min_checks:
        return True, f'GO: {facts} ({min_checks} checks make a desk)'
    if units >= min_units:
        return True, f'GO: {facts} ({min_units} steps make a desk)'
    if waited >= max_wait:
        return True, f'GO: {facts} (waited past {max_wait:g} h)'
    return False, f'STOP: {facts}; waiting for {min_checks} checks, {min_units} steps, or {max_wait:g} h'


def decide(batches, now, min_checks=MIN_CHECKS, min_units=MIN_UNITS, max_wait=MAX_WAIT_HOURS, force=False):
    """(go, verdict). When it is GO, the batch that earned it has been moved to the front of `batches`."""
    if not batches:
        return False, 'no unanswered /lane T4 requests'
    for index, batch in enumerate(batches):
        go, verdict = judge(batch, now, min_checks, min_units, max_wait)
        if go:
            batches.insert(0, batches.pop(index))
            return True, verdict
    return force, judge(batches[0], now, min_checks, min_units, max_wait)[1]


def age(created, now):
    hours = (now - parse_time(created)).total_seconds() / 3600
    return f'{hours:.0f} h' if hours < 48 else f'{hours / 24:.0f} d'


def render(batches, dropped, now, verdict):
    first = batches[0]
    where = ("the trunk's tip: build it once and install it on one pool device for every check below"
             if first['target'] == NEXT_TIP else f"commit {first['target']}: build it once and install it on one pool device for every check below")
    lines = [f'# Test Desk work list, {now:%Y-%m-%d %H:%M} UTC', '',
             f'{verdict}', '',
             f"- **Build:** {where}.",
             f"- **This batch:** {len(first['checks'])} check{'s' * (len(first['checks']) != 1)}, about {first['steps']} steps "
             f'(a desk finishes about {BUDGET} before its context runs out).',
             '- **Order:** take the checks in this order. Post one `Lane report <id> — PASS | FAIL | INCONCLUSIVE` per check on its PR '
             '(that is what takes it off the list). Screenshots cost about 2.5k tokens each: take one per step, not one per tap.',
             '- **If you run short:** stop between checks, post a hand-off on #184 and leave the rest. Unreported checks stay on the next list by themselves.', '']
    for index, check in enumerate(first['checks'], 1):
        issue = f", labels: {', '.join(check['labels'])}" if check['labels'] else ''
        lines += [f"## {index}. PR #{check['number']}: {check['title']}", '',
                  f"[Request]({check['url']}) by {check['author']}, {age(check['created'], now)} ago · "
                  f"{'merged' if check['merged'] else 'open'} · about {check['steps']} steps{issue}"]
        if check['note']:
            lines.append(f"Note: {check['note']}.")
        body = check['body']
        lines += ['', '```text', body if len(body) <= 3000 else body[:3000] + '\n[... cut; the request is at the link]', '```', '']
    if len(batches) > 1:
        lines += ['## Later batches', '']
        for number, batch in enumerate(batches[1:], 2):
            names = ', '.join(f"#{c['number']}" for c in batch['checks'])
            lines.append(f"{number}. {len(batch['checks'])} check(s) on {batch['target']}, about {batch['steps']} steps: {names}")
        lines.append('')
    if dropped:
        lines += ['## Left off', ''] + [f'- #{number}: {why}' for number, why in dropped] + ['']
    return '\n'.join(lines)


def plan(api, now, window_days=WINDOW_DAYS, budget=BUDGET, max_checks=MAX_CHECKS, journeys=None):
    since = (now - dt.timedelta(days=window_days)).strftime('%Y-%m-%dT%H:%M:%SZ')
    requests = pending_requests(comments_since(api, since), journey_steps() if journeys is None else journeys)
    checks, dropped = describe(api, requests)
    return make_batches(checks, budget, max_checks), dropped


def main(argv=None, api=None, now=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--print', action='store_true', help="print the first batch's work list")
    parser.add_argument('--force', action='store_true', help='write the work list even when the answer is STOP')
    parser.add_argument('--json', action='store_true', help='print the whole plan as JSON; write nothing')
    parser.add_argument('--window-days', type=float, default=WINDOW_DAYS, help='how far back to read comments (10)')
    parser.add_argument('--budget', type=int, default=BUDGET, help='steps per batch (24)')
    parser.add_argument('--max-checks', type=int, default=MAX_CHECKS, help='checks per batch (4)')
    parser.add_argument('--min-checks', type=int, default=MIN_CHECKS)
    parser.add_argument('--min-steps', type=int, default=MIN_UNITS)
    parser.add_argument('--max-wait-hours', type=float, default=MAX_WAIT_HOURS)
    parser.add_argument('--out-dir', type=Path, default=OUT_DIR)
    args = parser.parse_args(argv)
    now = now or dt.datetime.now(dt.timezone.utc)
    try:
        return run(args, api, now)
    except Exception as error:  # a broken setup must never look like a quiet queue (exit 1)
        print(f'ERROR: {type(error).__name__}: {error}', file=sys.stderr)
        return 2


def run(args, api, now):
    batches, dropped = plan(api or GitHub(), now, args.window_days, args.budget, args.max_checks)
    go, verdict = decide(batches, now, args.min_checks, args.min_steps, args.max_wait_hours, args.force)
    if args.json:
        slim = [{'target': b['target'], 'steps': b['steps'],
                 'checks': [{k: c[k] for k in ('number', 'title', 'url', 'steps', 'created', 'merged', 'note')} for c in b['checks']]}
                for b in batches]
        print(json.dumps({'verdict': verdict, 'batches': slim, 'dropped': dropped}, indent=2))
        return 0 if go else 1
    print(verdict)
    if not batches or not go:
        return 0 if go else 1
    text = render(batches, dropped, now, verdict)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    path = args.out_dir / f'desk-batch-{now:%Y%m%d-%H%M%S}.md'
    path.write_text(text, encoding='utf-8')
    (args.out_dir / 'latest.md').write_text(text, encoding='utf-8')
    print(f'work list: {path}')
    if len(batches) > 1:
        print(f'{len(batches) - 1} more batch(es) are waiting behind it')
    if args.print:
        print('\n' + text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
