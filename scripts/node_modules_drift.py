#!/usr/bin/env python3
"""Tell a thread to run `npm ci` when node_modules no longer matches package-lock.json (#2569).

npm writes node_modules/.package-lock.json listing what it actually installed. Comparing that with the
lockfile names the drift ("defuddle: installed 0.19.4, lock wants 0.19.5") before a bundle check fails with
a message that doesn't say what to do. Optional packages for other platforms are never installed, so a
missing optional package is not drift.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIX = 'run `npm ci` in the checkout that owns node_modules'


def drift(root: Path = ROOT) -> list[str]:
    """One line per package whose installed version differs from the lockfile, or is missing. Empty when it
    matches or when npm left no record to compare."""
    installed_path = root / 'node_modules' / '.package-lock.json'
    lock_path = root / 'package-lock.json'
    if not installed_path.is_file() or not lock_path.is_file():
        return []
    installed = json.loads(installed_path.read_text()).get('packages', {})
    locked = json.loads(lock_path.read_text()).get('packages', {})
    problems = []
    for key, entry in sorted(locked.items()):
        if not key or entry.get('link'):
            continue
        name = key.rsplit('node_modules/', 1)[-1]
        have = installed.get(key)
        if have is None:
            if not entry.get('optional'):
                problems.append(f'{name}: not installed, lock wants {entry.get("version")}')
        elif have.get('version') != entry.get('version'):
            problems.append(f'{name}: installed {have.get("version")}, lock wants {entry.get("version")}')
    return problems


def message(problems: list[str]) -> str:
    shown = '; '.join(problems[:5]) + (f'; and {len(problems) - 5} more' if len(problems) > 5 else '')
    return f'node_modules is out of date with package-lock.json ({shown}). {FIX.capitalize()}.'


def main() -> int:
    problems = drift()
    if problems:
        print(message(problems), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
