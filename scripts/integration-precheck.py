#!/usr/bin/env python3
"""Gate the SM integration understudy before a model starts. Stdlib, Python 3.9+."""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import datetime as dt
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
STATE = Path.home() / 'SpokenMarginsOps' / 'integration-precheck' / 'state.json'
REPO = 'Spoken-Margins/spoken-margins-native'
OWNER_LOGIN = 'uncomposed'  # the owner's GitHub login, not the repo's owner (#2169)
PROMPT_MARKER = '[SM-INTEGRATION-PRECHECK]'
LEGACY_TASK_PREFIXES = tuple(
    f'You are the Spoken Margins integration run, for the repo {repo}'
    for repo in ('uncomposed/spoken-margins-native', REPO)
)


def parse_time(value: str) -> dt.datetime:
    return dt.datetime.fromisoformat(value.replace('Z', '+00:00'))


def key(comment: dict) -> tuple:
    return (comment.get('updated_at') or comment.get('created_at') or comment.get('createdAt') or '',
            int(comment.get('id') or 0))


def posted_key(comment: dict) -> tuple:
    return (comment.get('created_at') or comment.get('createdAt') or '', int(comment.get('id') or 0))


def first_line(body: str) -> str:
    lines = body.strip().splitlines()
    if lines and lines[0].startswith('```'):
        lines = lines[1:]
    return next((line.strip().strip('* #') for line in lines if line.strip()), '')


def integration_report(comment: dict) -> dict | None:
    if not report_author(comment):
        return None
    body = comment.get('body') or ''
    first = first_line(body)
    match = re.match(r'(?:Lane report integration-|integration run\s+)([a-f0-9]{7,40})\s+[—-]\s+(PASS|FAIL|INCONCLUSIVE)\b', first, re.I)
    if match:
        sha, outcome = match.group(1).lower(), match.group(2).upper()
    else:
        desk = re.fullmatch(r'Codex Test Desk:\s*`?([a-f0-9]{7,40})`?', first, re.I)
        verdict = re.search(r'(?m)^(PASS|FAIL|INCONCLUSIVE)\s+—', body)
        if not desk or not verdict:
            return None
        sha, outcome = desk.group(1).lower(), verdict.group(1)
    commit = re.search(r'(?im)^commit\s+`?([a-f0-9]{7,40})', body)
    if commit:
        if not (commit.group(1).lower().startswith(sha) or sha.startswith(commit.group(1).lower())):
            raise ValueError('integration report heading/commit disagree')
        sha = commit.group(1).lower()
    return {'sha': sha, 'outcome': outcome, 'comment': comment}


def skip_head(comment: dict) -> str | None:
    body = comment.get('body') or ''
    if not report_author(comment) or not re.match(r'integration run skipped\b', first_line(body), re.I):
        return None
    match = re.search(r"next[’']s\s+tip[\s(`:]*([a-f0-9]{7,40})", body, re.I)
    return match.group(1).lower() if match else None


def trusted(comment: dict) -> bool:
    return (comment.get('user') or {}).get('login', '').casefold() == OWNER_LOGIN.casefold()


def report_author(comment: dict) -> bool:
    return trusted(comment) or (comment.get('user') or {}).get('login') == 'github-actions[bot]'


def is_desk(comment: dict) -> bool:
    if not report_author(comment):
        return False
    body = comment.get('body') or ''
    return bool(re.match(r'(?:Codex )?Test Desk\b', first_line(body), re.I) or
                re.search(r'(?im)^run by:\s*(?:Codex )?Test Desk\s*$', body))


def wake_event(comment: dict) -> bool:
    if not (trusted(comment) or is_desk(comment)):
        return False
    body = comment.get('body') or ''
    if re.search(r'(?im)^\s*/integration-retry\b', body):
        return True
    if integration_report(comment) or skip_head(comment):
        return False
    if is_desk(comment):
        return True
    first = first_line(body)
    if (re.search(r'\(\s*Mac tick\s*\)', first, re.I) or
            re.match(r'(?:Integration precheck|Mac tick|Lane report|Lane auto-revert|Codex audit|Codex hand-off|'
                     r'Thread |Finisher |Claimed by project thread)', first, re.I)):
        return False
    # Project jobs also post through the owner's account. A forwarded owner
    # decision is intentional context; generic generated job notes aren't.
    return 'Generated by [Claude Code]' not in body or first.startswith('Owner decision')


def blocker(report: dict, skip: dict | None = None) -> str | None:
    if report['outcome'] != 'INCONCLUSIVE':
        return None
    text = report['comment'].get('body') or ''
    if skip:
        text += '\n' + (skip.get('body') or '')
    causes = []
    if re.search(r'AddRunningClient failed|simulator.*audio.*(?:fail|fault)|audio output.*fail', text, re.I):
        causes.append('simulator audio did not start')
    if re.search(r'(?:hit|timed out|timeout).*cap|\b(?:600\s*s|plan).*(?:cap|timeout)', text, re.I):
        causes.append('the test plan hit its time cap')
    if re.search(r'disk (?:below|full)|no space left', text, re.I):
        causes.append('the Mac needs disk space')
    if not causes and re.search(r'needs?\s*:?\s*(?:an?\s+)?(?:person|owner)|manual intervention', text, re.I):
        causes.append('the report requires a person to resolve its blocker')
    return '; '.join(causes) if causes else None


@dataclass
class Decision:
    go: bool
    reason: str
    state: dict
    note: str | None = None
    note_key: str | None = None


def decide(tip: str, comments: list[dict], state: dict, now: dt.datetime) -> Decision:
    if not isinstance(state, dict):
        raise ValueError('saved state is not an object')
    reports = [r for c in comments if (r := integration_report(c))]
    report = max(reports, key=lambda r: posted_key(r['comment']), default=None)
    skips = [c for c in comments if skip_head(c)]
    skip = max(skips, key=posted_key, default=None)
    desks = [c for c in comments if c.get('issue') == 184 and is_desk(c)]
    desk = max(desks, key=key, default=None)
    held = bool(desk and now - parse_time(key(desk)[0]) < dt.timedelta(hours=3))
    baseline = posted_key(report['comment']) if report else ('', 0)
    previous = state.get('last_go') or {}
    if not isinstance(previous, dict):
        raise ValueError('saved launch state is not an object')
    consumed = tuple(previous.get('wake_key') or ('', 0))
    if len(consumed) != 2 or not isinstance(consumed[0], str) or type(consumed[1]) is not int:
        raise ValueError('saved trigger key is invalid')
    if consumed[0]:
        parse_time(consumed[0])
    events = [c for c in comments if wake_event(c) and key(c) > max(baseline, consumed)]
    event = max(events, key=key, default=None)
    matching = bool(report and (tip.startswith(report['sha']) or report['sha'].startswith(tip)))
    if not held and (event or (not matching and previous.get('tip') != tip)):
        updated = dict(state, last_go={'tip': tip, 'wake_key': list(key(event) if event else max(baseline, consumed))})
        return Decision(True, 'new owner/Test Desk context or retry' if event else 'new tip without a report', updated)
    reason = ('Test Desk posted on #184 within three hours' if held else
              'tip and reported outcome unchanged' if matching else
              'already launched on this tip; awaiting report or explicit retry')
    if skip and skip_head(skip) and tip.startswith(skip_head(skip)):
        reason += '; newest skip is on the same tip'
        outcome = re.search(r'\b(PASS|FAIL|INCONCLUSIVE)\b', skip.get('body') or '', re.I)
        reason += ' (' + (outcome.group(1).upper() if outcome else 'outcome unspecified') + ')'
    matching_skip = skip if skip and skip_head(skip) and tip.startswith(skip_head(skip)) else None
    cause = blocker(report, matching_skip) if matching else None
    if cause:
        identity = f"{tip}:{report['comment']['id']}:{hashlib.sha256(cause.encode()).hexdigest()[:12]}"
        marker = f'<!-- integration-precheck: {identity} -->'
        already = state.get('notified') == identity or any(
            trusted(c) and marker in (c.get('body') or '') for c in comments)
        if not already:
            url = report['comment'].get('html_url') or f'https://github.com/{REPO}/issues/184'
            note = (f'Integration precheck: blocked on `{tip[:7]}` (INCONCLUSIVE).\n\n'
                    f'Blocker: {cause}. [Last report]({url}).\n\n'
                    'To unblock: the owner or Test Desk should check the reported Mac/audio/plan problem, '
                    'then post new context or `/integration-retry` on #184 or #337. A new tip also reopens '
                    'the check. The three-hour Test Desk rule still applies.\n\n' + marker)
            return Decision(False, reason, state, note, identity)
    return Decision(False, reason, state)


def execute(ops, now: dt.datetime, dry_run=False) -> Decision:
    try:
        tip, comments = ops.snapshot()
        state = json.loads(ops.path.read_text()) if ops.path.exists() else {}
        decision = decide(tip, comments, state, now)
        if dry_run:
            return decision
        if decision.note:
            ops.post(decision.note)
            decision.state = dict(decision.state, notified=decision.note_key)
        if decision.state != state:
            ops.path.parent.mkdir(parents=True, exist_ok=True)
            temporary = ops.path.with_suffix('.tmp')
            with temporary.open('w') as saved:
                saved.write(json.dumps(decision.state) + '\n')
                saved.flush()
                os.fsync(saved.fileno())
            temporary.replace(ops.path)
        return decision
    except Exception as error:
        print(f'integration precheck unavailable: {error}', file=sys.stderr)
        return Decision(True, 'git/GitHub/state error; preserve existing behavior', {})


class Ops:
    def __init__(self, path=STATE):
        self.path = path

    def run(self, command):
        return subprocess.check_output(command, cwd=ROOT, text=True, stderr=subprocess.PIPE, timeout=120)

    def snapshot(self):
        from trunk import trunk_branch  # #1492: the branch the integration run tests
        branch = trunk_branch()
        self.run(['git', 'fetch', '--quiet', 'origin', f'refs/heads/{branch}:refs/remotes/origin/{branch}'])
        tip = self.run(['git', 'rev-parse', f'origin/{branch}']).strip()
        if not re.fullmatch(r'[a-f0-9]{40}', tip):
            raise ValueError(f'origin/{branch} is not a full commit SHA')
        comments = []
        for number in (184, 337):
            pages = json.loads(self.run(['gh', 'api', '--paginate', '--slurp',
                f'repos/{REPO}/issues/{number}/comments?per_page=100']))
            comments.extend(dict(c, issue=number) for page in pages for c in page)
        return tip, comments

    def post(self, body):
        path = self.path.parent / 'blocker-note.md'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
        result = self.run(['gh', 'api', '--method', 'POST', f'repos/{REPO}/issues/337/comments', '-F', f'body=@{path}'])
        return json.loads(result)['html_url']


def hook_target(payload: dict) -> bool:
    if not isinstance(payload, dict) or payload.get('hook_event_name') != 'UserPromptSubmit':
        return False
    prompt = payload.get('prompt')
    if not isinstance(prompt, str):
        return False
    text = prompt.lstrip('\ufeff \t\r\n')
    return text.startswith(PROMPT_MARKER) or text.startswith(LEGACY_TASK_PREFIXES)


def hook_output(decision: Decision) -> dict:
    if not decision.go:
        return {'decision': 'block', 'reason': 'STOP: ' + decision.reason,
                'hookSpecificOutput': {'hookEventName': 'UserPromptSubmit', 'suppressOriginalPrompt': True}}
    tip = (decision.state.get('last_go') or {}).get('tip')
    context = (f'Integration precheck GO for {tip or "the current tip (precheck unavailable)"}: {decision.reason}. '
               'This launch is already claimed. Do not run the precheck again. Use this decision for the '
               'tip/retry and Test Desk turn-taking gates; do not reapply older scheduling/head rules. '
               'Continue the existing integration procedure, retaining folder, simulator, disk/memory, '
               'crash-flood and owner-data guards. A new owner/Test Desk request can authorize the same tip.')
    return {'hookSpecificOutput': {'hookEventName': 'UserPromptSubmit', 'additionalContext': context}}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dry-run', action='store_true', help='read current state; post and save nothing')
    parser.add_argument('--state', type=Path, default=STATE)
    parser.add_argument('--claude-hook', action='store_true', help='read UserPromptSubmit JSON; block unchanged integration prompts before inference')
    args = parser.parse_args(argv)
    if args.claude_hook:
        try:
            payload = json.load(sys.stdin)
        except (ValueError, OSError) as error:
            print(f'integration hook unavailable: {error}', file=sys.stderr)
            return 0  # Same fail-open rule; never stall another task on malformed input.
        if not hook_target(payload):
            return 0
    ops = Ops(args.state)
    if args.dry_run:
        decision = execute(ops, dt.datetime.now(dt.timezone.utc), dry_run=True)
    else:
        try:
            ops.path.parent.mkdir(parents=True, exist_ok=True)
            with ops.path.with_suffix('.lock').open('a+') as lock:
                try:
                    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
                except BlockingIOError:
                    print('STOP: another integration precheck is running')
                    return 0
                decision = execute(ops, dt.datetime.now(dt.timezone.utc))
        except Exception as error:
            print(f'integration precheck unavailable: {error}', file=sys.stderr)
            decision = Decision(True, 'precheck unavailable', {})
    if args.claude_hook:
        print(json.dumps(hook_output(decision)))
    else:
        print('GO' if decision.go else 'STOP: ' + decision.reason)
    return 0


if __name__ == '__main__':
    sys.exit(main())
